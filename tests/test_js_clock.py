def test_no_step_of_the_scenario_widens_the_counter(clockwork):
    """Ширина частей -- не пожелание, и проверять её надо на каждом шаге.

    Ограничение счётчика стояло в ``tick`` и не стояло в ``receive``, а чужой
    счётчик приезжает из провода: ``ffff`` + 1 давал ``10000``, пять знаков.
    Такая отметка сортируется не позже всех, а **раньше**: ``'…118Z-10000-a' >
    '…118Z-ffff-a'`` -- ложь. Спор решается наоборот, и ни ошибки, ни отчёта.

    Сценарий его уже проходил (шаг с ``receive`` от ``ffff``), а смотрели
    только на то, что отметки растут, -- и растут они и с пятизначным
    счётчиком, потому что дальше сдвинулось время.
    """
    for stamps in [clockwork["played"], *clockwork["restarts"]]:
        assert all(STAMP.match(s) for s in stamps), stamps


def test_a_stamp_from_the_wire_cannot_drag_the_clock_into_the_future(clockwork):
    """Одна отметка из 2999 года выводила из строя весь парк, и необратимо.

    Часы поднимались до неё, поднятое уходило в ``hlc:last`` и переживало
    перезапуск -- то есть устройство до конца тысячелетия выигрывало любой спор
    и лечилось только правкой ``_oneframework_meta`` руками. Отказ громкий: это
    цена, названная вслух, а не поправка втихую, которая сделала бы приезжего
    победителем каждого спора.
    """
    текст = clockwork["fromTheWire"]
    assert текст, "отметка из 2999 года принята молча"
    assert FAR in текст and "стенные часы" in текст, текст

