@needs_node
def test_receiving_pulls_the_clock_up_on_both_sides(clockwork):
    """Ровно это и делает часы логическими: отстающее устройство после первого
    же обмена перестаёт выдавать отметки из прошлого."""
    ahead = at(BASE + 60_000)
    stamps = clockwork["played"]
    assert stamps[5] > ahead        # ответ на чужую отметку обгоняет её
    assert stamps[6] > stamps[5]    # и следующий свой tick не откатывается
    assert rises(stamps)


def test_a_stamp_sorts_as_a_plain_string():
    """Ради этого части и держат фиксированную ширину."""
    assert ZERO < at(0) < at(BASE) < at(BASE, 1) < at(BASE + 1)
    assert sorted([at(BASE, 16), at(BASE, 2)]) == [at(BASE, 2), at(BASE, 16)]


