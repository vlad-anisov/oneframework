#: Предел расхождения часов -- сутки. Записан здесь, а не спрошен у реализации:
#: проверка на то и проверка, чтобы называть число самой.
DRIFT_MAX_MS = 24 * 60 * 60 * 1000


def at(ms, counter=0, node="bbbbbbbb"):
    """Отметка **формулой**, а не вызовом реализации.

    Это и есть спецификация формата: год-месяц-день с миллисекундами тремя
    знаками, счётчик четырьмя шестнадцатеричными, узел восемью. Спроси мы её у
    той же реализации, которую проверяем, -- проверка сравнивала бы её с собой.
    """
    from datetime import datetime, timezone

    t = datetime.fromtimestamp(ms / 1000, timezone.utc)
    return f"{t.strftime('%Y-%m-%dT%H:%M:%S')}.{ms % 1000:03d}Z-{counter:04x}-{node}"


