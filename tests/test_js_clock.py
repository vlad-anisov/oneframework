HLC_JS_RUNNER = """
import { readFileSync } from "node:fs";
import { Clock, check, parse, nodeId, ZERO } from "%(hlc)s";

const payload = JSON.parse(readFileSync(process.argv[2], "utf8"));

function played(last, steps) {
  let step = 0;
  const clock = new Clock({ node: payload.node, last, now: () => steps[step++][1] });
  return steps.map(([op]) => (
    op === "tick" ? clock.tick() : clock.receive(op.slice("receive:".length))
  ));
}

const refusal = (call) => {
  try {
    call();
  } catch (err) {
    return err.message;
  }
  return null;
};
const wall = () => payload.wall;

process.stdout.write(JSON.stringify({
  zero: ZERO,
  played: played(null, payload.steps),
  restarts: payload.restarts.map(([last, steps]) => played(last, steps)),
  parsed: payload.stamps.map(parse),
  node: nodeId(),
  fresh: new Clock({}).tick(),
  wire: payload.wire.map((s) => refusal(() => check(s, wall))),
  fromTheWire: refusal(() => new Clock({ node: payload.node, now: wall }).receive(payload.far)),
  // Часы после отказа обязаны остаться рабочими: отказ не смеет бросить их на
  // полпути -- тогда устройство перестало бы стамповать вовсе.
  afterRefusal: (() => {
    const clock = new Clock({ node: payload.node, now: wall });
    const было = clock.tick();
    refusal(() => clock.receive(payload.far));
    return { before: было, after: clock.tick() };
  })(),
  ofItsOwn: refusal(() => new Clock({ node: payload.node, last: payload.far, now: wall }).tick()),
  beyondTheCalendar: payload.beyond.map((ms) => refusal(() => {
    const clock = new Clock({ node: payload.node, now: wall });
    clock.ms = ms;
    return clock.stamp();
  })),
}));
"""


