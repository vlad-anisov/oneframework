"""Каждая запись, которую умеет печатать язык, обязана читаться выборкой.

Причина этого файла -- не полнота ради полноты. За один день семья из пяти
одинаковых поломок вылезла четырьмя заходами: отрицание и связки нашлись
утром, сравнение -- вечером пробой обычного питона, `is None` и шаблон --
следом. Каждый раз причина была одна: выражение печатается **доменной**
записью (`{"op": "!", "e": …}`), а компилятор выборки читал только `args`.

Ловить это по одной записи бесполезно: находится ровно то, что попало в
корпус. Поэтому здесь перечисляются **все** узлы языка разом, и добавление
шестого без поддержки в выборке валит тест сразу, а не через месяц.
"""

import pytest

from oneframework.errors import DslError
from oneframework.model.expr import (
    And, Arith, Cmp, Count, Exists, IsNull, Max, Min, Not, Or, RecordFieldRef,
    Round, Sum, Template, TextExpr, _Lookup,
)
from oneframework.model.exprjson import to_json
from jsrel import call, needs_node

pytestmark = needs_node

ПОЛЕ = RecordFieldRef("done")
ЧИСЛО = RecordFieldRef("price")
СТРОКА = RecordFieldRef("title")

#: Все узлы, которые ``to_json`` умеет напечатать. Список сверяется с
#: реальными классами тестом ниже -- иначе он устареет молча.
УЗЛЫ = [
    ("ссылка", ПОЛЕ),
    ("сравнение", Cmp(">", ЧИСЛО, 100)),
    ("равенство", Cmp("=", СТРОКА, "Крыша")),
    ("и", And(ПОЛЕ, Cmp(">", ЧИСЛО, 1))),
    ("или", Or(ПОЛЕ, Cmp(">", ЧИСЛО, 1))),
    ("не", Not(ПОЛЕ)),
    ("пусто ли", IsNull(СТРОКА)),
    ("арифметика", Arith("+", [ЧИСЛО, 1])),
    ("деление", Arith("/", [ЧИСЛО, 2])),
    ("целочисленное деление", Arith("//", [ЧИСЛО, 2])),
    ("остаток", Arith("%", [ЧИСЛО, 2])),
    ("степень", Arith("**", [ЧИСЛО, 2])),
    ("минус", Arith("neg", [ЧИСЛО])),
    ("модуль", Arith("abs", [ЧИСЛО])),
    ("ветвление", Arith("if", [ПОЛЕ, 1, 0])),
    ("округление", Round(ЧИСЛО)),
    ("шаблон", Template([СТРОКА, ": ", ЧИСЛО])),
    # Строкой -- узел только на проводе: разворачивает его сборка, до
    # устройства он не доезжает. Произносится тем не менее: он попадается в
    # объявлении, и отказ, назвавший его номером, объяснял бы не то.
    ("выражение строкой", TextExpr("record.n > 3")),
    ("длина строки", Arith("length", [СТРОКА])),
    ("регистр", Arith("upper", [СТРОКА])),
    ("начинается с", Arith("startswith", [СТРОКА, "Кры"])),
    ("приведение к тексту", Arith("text", [ЧИСЛО])),
    ("точка через связь", _Lookup("board", RecordFieldRef("board_id"),
                                  RecordFieldRef("name"))),
    ("счёт", Count("Task", ПОЛЕ, via="board")),
    ("есть ли", Exists("Task", ПОЛЕ, via="board")),
    ("сумма", Sum("Task", None, via="board", of=RecordFieldRef("price"))),
    ("наименьшее", Min("Task", None, via="board", of=RecordFieldRef("price"))),
    ("наибольшее", Max("Task", None, via="board", of=RecordFieldRef("price"),
                       on_empty=0)),
]


#: Узлы, которые до выборки не доходят, и почему. Список, а не пропуск в теле:
#: исключение обязано быть названо, иначе следующий добавит своё молча.
#:
#: «выражение строкой» разворачивает сборка (`libs/js/src/build/plan.mjs`), и в
#: выложенный документ оно не попадает -- это проверено отдельно,
#: `tests/js/expr-text-wire.test.mjs`, «ни один текстовый узел не доживает до
#: плана». Требовать
#: от выборки читать строку значило бы возить разборщик на устройство.
НЕ_ДОЕЗЖАЮТ = {"выражение строкой"}


@pytest.mark.parametrize("имя,узел", УЗЛЫ, ids=[n for n, _ in УЗЛЫ])
def test_every_spelling_the_language_prints_is_read_by_the_query(имя, узел):
    """Напечатали -- значит обязаны прочитать. Исключения названы поимённо."""
    if имя in НЕ_ДОЕЗЖАЮТ:
        pytest.skip("узел разворачивается на сборке и до выборки не доходит")
    #: Читает та выборка, что стоит на устройстве: печатник питоновский, а
    #: разрыв между «напечатали» и «прочитали» надо ловить именно на ней.
    piece = call("compile_expr", to_json(узел))
    assert piece["sql"] and piece["sql"] != "NULL", f"{имя}: выборка ничего не собрала"


def test_the_list_above_covers_every_node_the_printer_knows():
    """Список узлов сверяется с самим печатником, а не живёт отдельно.

    Заведут шестую запись -- этот тест назовёт её по имени, и она не проедет
    молча мимо выборки, как проехали пять предыдущих.

    Кто у печатника ветка, спрашивается у :func:`~oneframework.model.exprschema
    .branch_classes` -- там же, откуда это узнаёт грамматика: два разбора
    одного и того же кода разошлись бы так же тихо, как два его описания.
    """
    from oneframework.model.exprschema import branch_classes

    печатает = {cls.__name__ for cls in branch_classes()}

    #: Не про формулы: ссылка вида и ссылка строки живут только в экране, где
    #: их разворачивает рантайм, а не выборка. ``Ref`` -- основание, ``Order``
    #: -- порядок сортировки.
    ЧУЖИЕ = {"Ref", "ViewFieldRef", "ItemFieldRef", "Order"}
    покрыто = {type(узел).__name__ for _, узел in УЗЛЫ}
    покрыто |= {"Aggregate"}                      # Count/Exists/Sum/Min/Max
    забыто = печатает - покрыто - ЧУЖИЕ
    assert not забыто, f"узлы языка не проверены выборкой: {sorted(забыто)}"


def test_the_exceptions_are_still_nodes_we_print():
    """Список исключений не должен пережить узел, ради которого заведён."""
    имена = {и for и, _ in УЗЛЫ}
    лишние = sorted(НЕ_ДОЕЗЖАЮТ - имена)
    assert not лишние, f"названы исключениями, а таких узлов нет: {лишние}"
