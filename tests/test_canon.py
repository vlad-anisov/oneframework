"""Каноническая запись: одна реализация и внешний судья.

Копий было две -- питоновская и браузерная. Питоновскую удалили 21.08.2026
вместе с выкладкой: отпечатки считает теперь та сторона, что пишет базу, и
второй записи правила не осталось.

Судья остался, и это важнее сверки копий: **сам JavaScript**. Правило печати
чисел взято у ECMAScript, значит эталон для него -- `String(число)` в node, а
не наше представление о нём. Числа поэтому и проверяются сравнением с ним.

Что ушло вместе с питоновской копией:

* сверка с **RFC 8785** -- она требовала питоновской библиотеки `rfc8785` и
  сравнивала с нею питоновскую же запись. Объявленное отступление от стандарта
  (порядок ключей вне основной плоскости) записано ниже отдельной проверкой,
  с числами, а не ссылкой на соседа;
* правило «большие целые едут собой». Выразить его на этой стороне нельзя:
  числа в JavaScript -- двойной точности, и `9007199254740993` становится
  `...992` **ещё в разборе JSON**, до всякой канонизации. На устройстве
  документ и приезжает разобранным JSON, поэтому обе стороны видят одно и то
  же double -- расхождения нет, а правила больше нет тоже.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from random import Random

import pytest

from conftest import needs_node

ROOT = Path(__file__).resolve().parents[1]
DRIVER = ROOT / "tests" / "parity" / "canon_driver.mjs"

pytestmark = needs_node

#: Пробы -- по одному правилу на имя, чтобы проверка называла правило, а не
#: индекс в списке.
ПРОБЫ = {
    "порядок": {"b": 1, "a": 2},
    "астраль": {"\U0001d11e": 1, "z": 2},
    # Именно эта пара различает два порядка: по кодовым точкам "￿"
    # (65535) идёт раньше "\U0001d11e" (119070), а по кодовым единицам UTF-16
    # -- позже, потому что суррогатная пара начинается с 0xd834 (55348).
    "различение": {"￿": "bmp", "\U0001d11e": "astral"},
    "целое": {"x": 3.0},
    "нольминус": {"x": -0.0},
    "e16": {"x": 1e16},
    "e21": {"x": 1e21},
    "e_5": {"x": 1e-5},
    "e_7": {"x": 1e-7},
    "экранирование": {"esc": 'a"b\\c\nd\te'},
    "отпечаток": {"a": 1},
    "пустойсписок": [],
    "пустаякарта": {},
}

#: Числа отдельно от документов: правило их печати -- то место, где языки
#: расходятся первым, и точные значения удобнее держать литералом.
ЧИСЛА = [3.0, -0.0, 1.5, 0.1, 2.675, 1e16, 1e21, 1e-7, 1e-5, 1e-6, 100.0,
         -2.5, 1e20, 1.23e-7, 5e-324, 1.7976931348623157e308, 0.0001]

_ОТВЕТ = None


def ответ():
    global _ОТВЕТ
    if _ОТВЕТ is None:
        ввод = {"probes": ПРОБЫ, "numbers": [repr(ч) for ч in ЧИСЛА], "docs": []}
        готово = subprocess.run(["node", str(DRIVER)], input=json.dumps(ввод, ensure_ascii=False),
                                capture_output=True, text=True, encoding="utf-8", cwd=str(ROOT))
        assert готово.returncode == 0, готово.stderr
        _ОТВЕТ = json.loads(готово.stdout)
    return _ОТВЕТ


def текст(имя):
    п = ответ()["probes"][имя]
    assert "error" not in п, (имя, п["error"])
    return п["text"]


# ==========================================================================
# сама запись
# ==========================================================================
def test_keys_are_ordered_by_code_point():
    """Порядок ключей -- по кодовым точкам, а не по единицам UTF-16.

    Различает их только ключ вне основной плоскости, и он в пробах есть.
    `Array.prototype.sort` без сравнителя даёт **обратный** порядок на такой
    паре, и до 21.08.2026 это ловила только сверка с питоном: подмена
    сравнителя на умолчание оставляла всю сюиту зелёной (проверено мутацией).
    """
    assert текст("порядок") == '{"a":2,"b":1}'
    assert текст("астраль") == '{"z":2,"\U0001d11e":1}'
    assert текст("различение") == '{"￿":"bmp","\U0001d11e":"astral"}'


def test_numbers_follow_javascript():
    """Печать чисел -- та же, что у `String(число)`: это правило ECMAScript."""
    assert текст("целое") == '{"x":3}'
    assert текст("нольминус") == '{"x":0}'
    assert текст("e16") == '{"x":10000000000000000}'
    assert текст("e21") == '{"x":1e+21}'
    assert текст("e_5") == '{"x":0.00001}'
    assert текст("e_7") == '{"x":1e-7}'


def test_strings_are_escaped_the_json_way():
    """Кавычка, слеш, перевод строки и табуляция -- обычным экранированием."""
    assert текст("экранирование") == '{"esc":"a\\"b\\\\c\\nd\\te"}'


def test_infinity_is_refused_rather_than_fingerprinted():
    """Документ, который нельзя записать, не должен получать имя.

    Получи он отпечаток -- уехал бы обменом, и разобрать его на той стороне
    было бы нечем.
    """
    for имя in ("бесконечность", "минусбесконечность", "ненеЧисло"):
        п = ответ()["probes"][имя]
        assert "error" in п, f"{имя}: записалось как {п.get('text')!r}"
        assert "бесконечност" in п["error"] or "nan" in п["error"].lower(), п["error"]


def test_fingerprint_is_sixteen_hex_characters():
    fp = ответ()["probes"]["отпечаток"]["fp"]
    assert len(fp) == 16 and int(fp, 16) >= 0


def test_distinct_documents_get_distinct_fingerprints():
    """Пустой список и пустая карта -- разные документы, значит разные имена."""
    assert (ответ()["probes"]["пустойсписок"]["fp"]
            != ответ()["probes"]["пустаякарта"]["fp"])


