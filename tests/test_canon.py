def test_the_number_rule_matches_string_of_a_double():
    """Печать берётся у ECMAScript, значит и сверяется с ним -- на его числах.

    Список выше -- краевые случаи, выбранные руками; здесь тысяча случайных
    двойных, каких руками не придумать.
    """
    случай = Random(20260821)
    числа = [случай.uniform(-1e6, 1e6) for _ in range(500)]
    числа += [случай.uniform(-1e-6, 1e-6) for _ in range(500)]

    ввод = {"probes": {}, "docs": [], "numbers": [repr(ч) for ч in числа]}
    готово = subprocess.run(["node", str(DRIVER)], input=json.dumps(ввод),
                            capture_output=True, text=True, encoding="utf-8", cwd=str(ROOT))
    assert готово.returncode == 0, готово.stderr
    напечатано = json.loads(готово.stdout)["numbers"]

    ввод2 = {"probes": {f"n{i}": {"x": ч} for i, ч in enumerate(числа)},
             "docs": [], "numbers": []}
    готово2 = subprocess.run(["node", str(DRIVER)], input=json.dumps(ввод2),
                             capture_output=True, text=True, encoding="utf-8", cwd=str(ROOT))
    assert готово2.returncode == 0, готово2.stderr
    пробы = json.loads(готово2.stdout)["probes"]

    for i, (ч, как) in enumerate(zip(числа, напечатано)):
        assert пробы[f"n{i}"]["text"] == '{"x":%s}' % как, (ч, как, пробы[f"n{i}"])
