/**
 * Выражение строкой доезжает от привязки до выложенного документа.
 *
 * Узел `{"text": "..."}` живёт только на проводе: привязке дешевле передать
 * строку, чем встраивать в свой язык четырнадцать родов узлов. Разворачивает
 * его сборка, и в базу едет то же дерево, что и от питоновского приложения.
 *
 * Проверяется вся дорога: что текст вправду разворачивается по пути и что
 * неразобранное до устройства не доезжает. Сам разборщик -- ниже, свёртками:
 * сверять его с питоновским DSL больше не с чем, DSL стал этой же строкой.
 */

import test, { before } from "node:test";
import assert from "node:assert/strict";

import { Bundle } from "../../src/build/bundle.mjs";
import { buildPlan } from "../../src/build/plan.mjs";
import { parseExpr } from "../../src/build/exprtext.mjs";
import { подопытноеTodo } from "./помощь.mjs";

let исходный = null;
before(async () => { исходный = await подопытноеTodo(); });

/** Своя копия пакета на проверку: каждая его правит по-своему. */
const пакет = () => structuredClone(исходный);
const план = (п) => buildPlan(new Bundle(п).doc);
const вид = (п, имя) => п.defs.find((д) => д[0] === "view" && д[1] === имя)[2];

/** Сравнение по содержимому, а не по записи: порядок ключей тут не правило. */
const одинаково = (a, b) => assert.deepEqual(a, b);

test("строка разворачивается в то же дерево, что положил бы питон", () => {
  const п = пакет();
  // Первый вид, у которого поле лежит прямо в детях: у иных они внутри строк
  // и групп, и добираться туда проверке не за чем.
  let номер = -1, место = -1;
  п.views.forEach((в, i) => {
    if (номер >= 0) return;
    const j = (в.children || []).findIndex((н) => н.type === "field");
    if (j >= 0) { номер = i; место = j; }
  });
  assert.ok(номер >= 0, "в пакете нет вида с полем прямо в детях");
  const имя = п.views[номер].name;

  const деревом = пакет();
  деревом.views[номер].children[место].visible = { op: ">", l: { r: "sequence" }, r: 3 };
  const строкой = пакет();
  строкой.views[номер].children[место].visible = { text: "record.sequence > 3" };

  одинаково(вид(план(строкой), имя), вид(план(деревом), имя));
});

test("ни один текстовый узел не доживает до плана", () => {
  // В выложенном документе строк быть не должно -- рантайм их не разбирает.
  // Пропусти сборка неразвёрнутый узел, устройство получило бы условие,
  // которое не умеет читать: экран нарисовался бы без поля, и связать пустоту
  // со строкой было бы нечем.
  const п = пакет();
  п.views[0].children[0].visible = { text: "record.completed" };
  const виды = план(п).defs.filter((д) => д[0] === "view");
  // Поля с именем `text` -- не узлы: их запись заменяется, чтобы не спутать.
  assert.ok(!JSON.stringify(виды).replaceAll('"text":"', '"ЗНАЧЕНИЕ":"').includes('"text":'));
});

test("неразобранное останавливает сборку", () => {
  const п = пакет();
  п.views[0].children[0].visible = { text: "record.n @@ 3" };
  assert.throws(() => план(п), /непонятный знак/);
});

test("текстовый узел не путают с виджетом «текст»", () => {
  // Узел вида «текст» и действие `text` -- не выражения, их трогать нельзя.
  // Признак разворачивания -- ровно один ключ `text`; совпадения по одному
  // имени ключа хватило бы, чтобы развернуть не то.
  const п = пакет();
  п.views[0].children.push({ type: "text", id: "V.t1", value: "просто слова" });
  const узлы = вид(план(п), п.views[0].name).children;
  assert.equal(узлы.find((н) => н.type === "text").value, "просто слова");
});

test("узел, у которого ключ text просто есть, не трогают", () => {
  // Разворачивается объект, у которого `text` -- **единственный** ключ.
  // Сегодня ключа `text` не несёт ни один узел договора, и хватило бы
  // вхождения. Строго -- ради завтрашнего: заведут узел вида с подписью в
  // ключе `text`, и вхождение развернуло бы подпись в выражение.
  const п = пакет();
  п.views[0].children.push({ type: "text", id: "V.t9", text: "record.done" });
  const узлы = вид(план(п), п.views[0].name).children;
  assert.equal(узлы.find((н) => н.id === "V.t9").text, "record.done",
               "подпись развернули в выражение");
});

test("выражение строкой, которое не строка, отвергнуто", () => {
  // Пропущенное доедет до устройства, где его никто не прочтёт: условие не
  // сработает, поле не нарисуется, и связать это с записью будет нечем.
  const п = пакет();
  п.views[0].children[0].visible = { text: { r: "done" } };
  assert.throws(() => план(п), /записывается строкой/);
});

test("выражение строкой внутри действия тоже разворачивается", () => {
  // Правило и правка объявленного действия -- тоже выражения. Их разворот
  // отдельной строкой в коде, и без этой проверки снятая строка оставляла
  // сюиту зелёной: у примеров объявленных действий нет.
  const п = пакет();
  п.logic = [{ actions: [{
    name: "TodoLine.поднять",
    label: "поднять",
    model: "TodoLine",
    args: [{ name: "ids", type: "ids" }],
    returns: [{ name: "records", type: "json" }],
    rule: { text: "record.sequence > 3" },
    write: { sequence: { text: "record.sequence + 10" } },
  }] }];
  const действие = план(п).defs.find((д) => д[0] === "action")[2];
  assert.deepEqual(действие.rule, { op: ">", l: { r: "sequence" }, r: 3 });
  assert.deepEqual(действие.write.sequence, { op: "+", args: [{ r: "sequence" }, 10] });
});

test("выражение строкой внутри модели тоже разворачивается", () => {
  // Вычисляемое поле модели -- тоже выражение, и тоже строкой. Разворот
  // моделей -- отдельная строка в коде, и без этой проверки снятая строка
  // оставляла сюиту зелёной: у примеров вычисляемых полей строкой нет.
  const п = пакет();
  const модель = п.models[0];
  модель.fields.push({ name: "громко", ftype: "string", label: "Громко",
                       compute: { text: "upper(record.name)" } });
  const свой = план(п).defs.find((д) => д[0] === "model" && д[1] === модель.name)[2];
  assert.deepEqual(свой.fields.find((f) => f.name === "громко").compute,
                   { op: "upper", args: [{ r: "name" }] });
});

// --------------------------------------------------------------------------
// свёртки: count/exists/sum/min/max
// --------------------------------------------------------------------------
//: Свёртки -- пятая часть договора выражений, и до сих пор строкой их было не
//: записать: разборщик знал ссылки, сравнения и арифметику, но не «сколько
//: записей другой модели отвечают условию». Значит текстовая дорога была
//: беднее питоновской, и объявить одно и то же на трёх языках было нельзя.
test("свёртка строкой даёт то же дерево, что перегрузка операторов", () => {
  // Слово в слово то, что печатает `Exists(Task, (record.board == item.id) &
  // record.done)` у питоновской привязки. Сверено с ней при переносе.
  assert.deepStrictEqual(
    parseExpr("exists(Task, record.board = item.id & record.done)"),
    { agg: "exists", model: "Task",
      domain: { op: "&", p: [{ op: "=", l: { r: "board" }, r: { i: "id" } },
                             { r: "done" }] } });
});

test("домен необязателен: свёртка по всей модели", () => {
  assert.deepStrictEqual(parseExpr("count(Task)"), { agg: "count", model: "Task" });
});

test("что складывать -- отдельным доводом перед доменом", () => {
  const дерево = parseExpr("sum(Task, record.price, record.done)");
  assert.deepStrictEqual(дерево.of, { r: "price" });
  assert.deepStrictEqual(дерево.domain, { r: "done" });
});

test("via и on_empty пишутся именованными -- порядок не надо помнить", () => {
  const дерево = parseExpr("sum(Task, record.price, via=board, on_empty=0)");
  assert.strictEqual(дерево.via, "board");
  assert.strictEqual(дерево.on_empty, 0);
  // Домена нет, и это не то же, что пустой домен: без него свёртка идёт по
  // всей модели, а `domain: null` означало бы условие, которого нет.
  assert.ok(!("domain" in дерево));
});

test("именованный довод после домена не путается с ним", () => {
  const дерево = parseExpr("count(Task, record.done, on_empty=0)");
  assert.deepStrictEqual(дерево.domain, { r: "done" });
  assert.strictEqual(дерево.on_empty, 0);
});

test("неизвестный именованный довод -- отказ, а не пропуск", () => {
  // Молча проглоченный довод уехал бы свёрткой без него: число на экране
  // другое, и связать его с опечаткой нечем.
  assert.throws(() => parseExpr("count(Task, record.done, чего=1)"), /чего/);
});

test("модель называется словом, а не строкой", () => {
  assert.throws(() => parseExpr('count("Task")'), /ждали слово/);
});

test("свёртка без модели отвергнута", () => {
  assert.throws(() => parseExpr("count()"), /ждали слово/);
});
