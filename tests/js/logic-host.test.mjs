/**
 * Договор хоста с объявленным действием: что оно может и как отказывает.
 *
 * Правило не формальность. База ведёт учёт правок для обмена, и запись мимо неё
 * не уехала бы на другие устройства -- разошлись бы молча. Поэтому действие
 * возвращает записи, а кладёт их хост, сверяясь со списком `writes` из
 * объявления.
 *
 * Почему этот файл появился 21.08.2026. Правило было записано дважды: у
 * питоновского исполнителя (`rel/action.py`) и у того, что стоит на устройстве
 * (`src/runtime/logic.js`). Сторожила его только первая запись --
 * та, которая на устройстве не исполняется ни разу. Проверено мутацией: снятый
 * список разрешённых полей в `logic.js` оставлял **всю сюиту зелёной**.
 *
 * Действие здесь на JavaScript, и это не случайность: его исполняет сам движок.
 * Питоновскому нужен Pyodide, а под node его не поднять -- `import()` принимает
 * `file:`, `fetch` принимает `http:`, и одного значения, годного обоим, нет.
 *
 * Объявление написано **руками**, а не собрано из метода. Так и надо:
 * собранное всегда согласовано с телом, а проверяется здесь как раз то, что
 * делает хост с несогласованным -- то есть с ответом, где полей больше, чем
 * разрешено.
 */

import test, { before } from "node:test";
import assert from "node:assert/strict";

import { поднятьПлан } from "./помощь.mjs";

let основа = null;

before(async () => {
  const { Button, Logic, Screen, app, boolean, declare, model, string, view } =
    await import("../../../oneframework-js/index.mjs");
  const { Bundle } = await import("../../src/build/bundle.mjs");
  const { buildPlan } = await import("../../src/build/plan.mjs");

  const Листок = model("Листок", {
    table: "листок",
    fields: { name: string("Имя"), done: boolean("Готово") },
  });
  const Стол = view("Стол", {
    model: Листок,
    // Кнопка нужна проверке отказа: нажатие возвращается в рантайм номером
    // кнопки, и без неё в кадре дойти до действия нечем. `Logic("имя")`
    // строкой -- потому что объявление здесь рукописное, метода за ним нет.
    ui: () => [
      Button("Тронуть", { action: Logic("Листок.тронуть") }),
      // Второе действие набора **не просит**: без него правило «нужен набор»
      // не отличить от «нужен всегда» -- переусердствовавшая проверка
      // запретила бы законное, и сюита осталась бы зелёной.
      Button("Само", { action: Logic("Листок.само") }),
    ],
  });
  const приложение = app({
    title: "Листки", models: [Листок], views: [Стол],
    screens: [Screen(Стол)], root: Стол,
  });
  const пакет = declare(приложение);
  основа = { план: buildPlan(new Bundle(пакет).doc), экраны: пакет.app.screens ?? [] };
});

//: Тело действия. Возвращает **оба** поля, хотя разрешено ему одно: ровно тот
//: случай, ради которого хост и сверяется со списком.
const ИСХОДНИК = `
exports.__oneframework_entry = function (кадр) {
  return { records: (кадр.records || []).map((r) => ({
    id: r.id, name: "переписано", done: true,
  })) };
};
`;

const ТРОНУТЬ = {
  name: "Листок.тронуть", label: "тронуть", model: "Листок",
  args: [{ name: "ids", type: "ids" }],
  returns: [{ name: "records", type: "json" }],
  language: "javascript",
  js: { entry: "__oneframework_entry", source: ИСХОДНИК, writes: ["name"] },
};

//: Действие без аргумента-набора: оно работает само по себе, и записи ему не
//: нужно. Тело то же -- важно объявление.
const САМО = { ...ТРОНУТЬ, name: "Листок.само", label: "само", args: [] };

//: Объявление, у которого названной функции нет вовсе.
const БЕЗ_ТОЧКИ = {
  ...ТРОНУТЬ, name: "Листок.нет", label: "нет",
  js: { entry: "отсутствует", source: "exports.другая = () => ({});\n", writes: ["name"] },
};

//: Объявление, чей текст падает при исполнении, но разбирается при загрузке.
const ПАДАЮЩЕЕ = {
  ...ТРОНУТЬ, name: "Листок.падает", label: "падает",
  js: { entry: "__oneframework_entry", writes: ["name"],
        source: 'exports.__oneframework_entry = function () {\n'
                + '  throw new Error("ошибка внутри действия");\n};\n' },
};

/** Приложение с рукописными объявлениями, собранное как настоящее. */
async function поднять(...объявления) {
  const план = structuredClone(основа.план);
  for (const д of объявления) план.defs.push(["action", д.name, д]);
  const { rt, db, модели } = await поднятьПлан(план, основа.экраны);
  return { rt, db, Листок: модели["Листок"] };
}

const действия = (rt) => Object.keys(rt.logic?.actions ?? {}).sort();

/** Все кнопки кадра, в порядке обхода: нажатие возвращается номером. */
function кнопки(кадр) {
  const найдено = [];
  const обойти = (узел) => {
    if (Array.isArray(узел)) { узел.forEach(обойти); return; }
    if (!узел || typeof узел !== "object") return;
    if (узел.type === "button") найдено.push(узел);
    for (const значение of Object.values(узел)) обойти(значение);
  };
  обойти(кадр);
  assert.ok(найдено.length, `в кадре нет кнопки: ${Object.keys(кадр)}`);
  return найдено;
}

const кадр = (rt) => rt.snapshot().stacks[rt.snapshot().active].at(-1);

test("действие вообще доехало", async () => {
  // Сначала это: иначе проверки ниже пусты.
  const { rt } = await поднять(ТРОНУТЬ, САМО);
  assert.deepEqual(действия(rt), ["Листок.само", "Листок.тронуть"]);
});

test("хост пишет разрешённое поле", async () => {
  // Иначе действие бесполезно.
  const { rt, db, Листок } = await поднять(ТРОНУТЬ, САМО);
  const ключ = db.create(Листок, { name: "было", done: false });
  await rt.logicAction("Листок.тронуть")({ ids: [ключ] });
  assert.equal(db.read(Листок, ключ).name, "переписано");
});

test("хост отвергает поле, которого не заявляли", async () => {
  // Главное правило файла. Действие вернуло `done`, хотя объявило
  // `writes: ["name"]`. Хост обязан его отбросить. Без этой проверки список
  // разрешённых полей можно было снять целиком, и ни один прогон бы не заметил.
  const { rt, db, Листок } = await поднять(ТРОНУТЬ, САМО);
  const ключ = db.create(Листок, { name: "было", done: false });
  await rt.logicAction("Листок.тронуть")({ ids: [ключ] });
  const стало = db.read(Листок, ключ);
  assert.ok(стало.done === 0 || стало.done === false,
            `записалось незаявленное: ${JSON.stringify(стало)}`);
});

test("пропавшая точка входа названа", async () => {
  // Названной функции нет -- отказ обязан назвать и её, и что есть. Иначе
  // человек видит «действие не сработало» и идёт искать причину в базе, в
  // правах, в чём угодно, кроме опечатки в имени.
  const { rt } = await поднять(БЕЗ_ТОЧКИ);
  await assert.rejects(() => rt.logicAction("Листок.нет")({ ids: [] }), (беда) => {
    assert.match(беда.message, /отсутствует/);
    assert.match(беда.message, /другая/, "отказ не сказал, что в объявлении есть");
    return true;
  });
});

test("падающее действие не мешает подъёму", async () => {
  // Текст исполняется при вызове, а не при загрузке: иначе одна опечатка в
  // одном действии не даёт открыть приложение вовсе, и починить её негде.
  const { rt } = await поднять(ПАДАЮЩЕЕ);
  assert.deepEqual(действия(rt), ["Листок.падает"], "приложение не поднялось");
  await assert.rejects(() => rt.logicAction("Листок.падает")({ ids: [] }),
                       /ошибка внутри действия/);
});

test("неизвестное действие называет объявленные", async () => {
  // Опечатка в виде -- отказ, называющий известные имена, а не пустой экран.
  const { rt } = await поднять(ТРОНУТЬ, САМО);
  assert.throws(() => rt.logicAction("Листок.трнуть"), /Листок\.тронуть/);
});

test("хост отказывает действию без записи в кадре", async () => {
  // Действию нужен набор, а записи нет -- отказ вслух, а не работа впустую.
  //
  // До 21.08.2026 такое действие исправно исполнялось над **пустым** набором:
  // проходило успешно и не меняло ничего. На экране это выглядело как кнопка,
  // которая молчит, -- ни ответа, ни отказа, ни следа. Замерено на всех трёх
  // примерах тройки, то есть поведение было каркасное, а не языковое.
  //
  // Кнопку на черновике теперь гасит сам рантайм
  // (`tests/e2e/notes-kotlin.spec.js`), но сюда можно прийти и мимо неё --
  // адресом, действием строки, чужим вызовом. Поэтому рубежа два.
  const { rt } = await поднять(ТРОНУТЬ, САМО);
  const к = кадр(rt);
  assert.throws(() => rt.dispatch({
    type: "action", button_id: кнопки(к)[0].id,
    context: { screen_id: к.id, model: "Листок", record_id: null, in_row: false },
  }), /ещё не создана/);
});

test("то же нажатие срабатывает, когда запись есть", async () => {
  // Иначе отказ выше запретил бы законное: правило звучит «набор пуст», а не
  // «действия нельзя».
  const { rt, db, Листок } = await поднять(ТРОНУТЬ, САМО);
  const ключ = db.create(Листок, { name: "было", done: false });
  const к = кадр(rt);
  // Ожиданием: `dispatch` отдаёт обещание наружу -- логика на устройстве почти
  // всегда асинхронна, и снимок без ожидания уходит до записи.
  await rt.dispatch({
    type: "action", button_id: кнопки(к)[0].id,
    context: { screen_id: к.id, model: "Листок", record_id: ключ, in_row: false },
  });
  assert.equal(db.read(Листок, ключ).name, "переписано");
});

test("кто набора не просил, тому запись и не нужна", async () => {
  // Иначе правило «нужен набор» выродилось бы в «нужен всегда», и отказ
  // запретил бы законное. Замерено: без этой проверки переусердствовавшее
  // правило оставляло сюиту зелёной.
  const { rt } = await поднять(ТРОНУТЬ, САМО);
  const к = кадр(rt);
  const само = кнопки(к).find((б) => б.label === "Само");
  // Без записи и без отказа: тело ничего не найдёт в пустом кадре и вернёт
  // пустой ответ -- это законный исход, а не молчание вместо работы.
  await rt.dispatch({
    type: "action", button_id: само.id,
    context: { screen_id: к.id, model: "Листок", record_id: null, in_row: false },
  });
});
