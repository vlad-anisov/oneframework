/**
 * Грамматика выражений -- одна, и это сторож при ней.
 *
 * Дерево выражения ездит между тремя языками объявления и двумя вычислителями.
 * Разойдись стороны в форме узла -- и он приезжает не ошибкой, а не тем
 * условием, то есть не тем списком на экране. Заметить это можно только по
 * чужой жалобе.
 *
 * Описание одно -- `protocol/expression.json`, -- и оно **источник**, а не
 * вывод. Читают его все, и сверяются с ним тоже все.
 *
 * Здесь, а не на питоне, потому что предмет ядерный: разборщик, компилятор и
 * договор -- всё это ядро, и питон в проверке не участвовал ничем, кроме того,
 * что на нём она была написана. Одно исключение осталось у него:
 * `tests/together/test_grammar_apps.py` берёт настоящие приложения на питоне и
 * смотрит, отвечают ли договору их выражения. Для этого нужны обе стороны,
 * и живёт оно там, где обе есть.
 *
 * Сторожа ловят разные способы разойтись:
 *
 * 1. **образец против самого себя** -- по образцу род узнаётся однозначно;
 * 2. **написание против выборки** -- то, что можно написать, обязано быть
 *    прочитано, и прочитано **тем родом**;
 * 3. **слова арифметики против компилятора** -- слово, которое разборщик умеет
 *    породить, а SQL перевести не умеет, откажет уже у человека;
 * 4. **библиотека для JavaScript против образцов** -- тот же узел собрался
 *    другой записью. Сверяется побайтно: «похоже» здесь не значит ничего.
 *
 * Отдельно проверяется, что сторож умеет ругаться: описание, по которому не
 * падает ни одно испорченное дерево, не проверяет ничего.
 */
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import path from "node:path";
import test, { describe } from "node:test";
import { fileURLToPath } from "node:url";

import { compileExpr } from "../../src/rel/compile.js";
import { развернутьТекст } from "../../src/build/plan.mjs";
import { ГРАММАТИКА, беды, узнать } from "./грамматика.mjs";

const ЗДЕСЬ = path.dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = path.resolve(ЗДЕСЬ, "..", "..");
const ДРАЙВЕР = path.join(КОРЕНЬ, "tests", "parity", "expr_grammar_driver.mjs");

/** Строка -> дерево, тем же разборщиком, каким её разворачивает сборка. */
const разобрать = (текст) => развернутьТекст({ text: текст });

// --------------------------------------------------------------------------
// написания
// --------------------------------------------------------------------------
/**
 * Написание -> род узла, который оно обязано дать.
 *
 * Род называется явно и **сверяется**: иначе опечатка в написании тихо
 * проверяла бы не тот узел. Так и было -- `record.title = null` числился как
 * `is_null`, а собирался сравнением с пустотой, и `is_null` не проверялся
 * вовсе.
 */
const НАПИСАНИЯ = [
  ["record.done", "record_ref"],
  ["record.price > 100", "cmp"],
  ['record.title = "Крыша"', "cmp"],
  ["record.done & record.price > 1", "and"],
  ["record.done | record.price > 1", "or"],
  ["!record.done", "not"],
  ["record.title is null", "is_null"],
  ["record.title is not null", "not"],
  ["record.price + 1", "arith"],
  ["record.price / 2", "arith"],
  ["record.price % 2", "arith"],
  ["record.price ** 2", "arith"],
  ["-record.price", "arith"],
  ["abs(record.price)", "arith"],
  ["if(record.done, 1, 0)", "arith"],
  ["round(record.price)", "arith"],
  ["length(record.title)", "arith"],
  ["upper(record.title)", "arith"],
  ['startswith(record.title, "Кры")', "arith"],
  ["text(record.price)", "arith"],
  ["count(Task, record.done, via=board)", "aggregate"],
  ["exists(Task, record.done, via=board)", "aggregate"],
  ["sum(Task, record.price, via=board)", "aggregate"],
  ["min(Task, record.price, via=board)", "aggregate"],
  ["max(Task, record.price, via=board, on_empty=0)", "aggregate"],
];

/**
 * Роды договора без написания, и почему. Список, а не пропуск в теле:
 * исключение обязано быть названо, иначе следующий добавит своё молча.
 */
const БЕЗ_НАПИСАНИЯ = new Set([
  // Узел «строкой» -- это и есть то, чем написано всё остальное. Написать его
  // написанием нельзя: он был бы строкой внутри строки.
  "text",
  // Шаблон и порядок строит привязка, а не разборщик: `f"{record.name}"` и
  // `record.date.desc()` -- части объявления вида, а не выражения.
  "template", "order",
  // «Не выбрано» -- состояние экрана, а не написанное условие.
  "unset",
  // Точка через связь -- вывод компилятора, а не написание.
  "lookup",
  // Ссылка вида и ссылка строки требуют обстановки -- состояния экрана и
  // разворачиваемой записи, -- а `compileExpr` спрашивают без неё. Их сторожит
  // `tests/together/test_dsl.py`, где обстановка есть.
  "view_ref", "item_ref",
]);

describe("написания", () => {
  for (const [написание, род] of НАПИСАНИЯ) {
    test(`читается выборкой и тем родом: ${написание}`, () => {
      const дерево = разобрать(написание);
      assert.equal(узнать(дерево), род, `${написание} собралось как ${узнать(дерево)}`);
      const кусок = compileExpr(дерево, { table: "t" });
      assert.ok(кусок.sql && кусок.sql !== "NULL",
                `${написание}: выборка ничего не собрала`);
    });
  }

  test("написания покрывают весь договор", () => {
    const покрыто = new Set(НАПИСАНИЯ.map(([, род]) => род));
    const забыто = Object.keys(ГРАММАТИКА.nodes)
      .filter((род) => !покрыто.has(род) && !БЕЗ_НАПИСАНИЯ.has(род));
    assert.deepEqual(забыто, [], `роды договора не проверены выборкой: ${забыто}`);
  });

  test("исключения переживают только свои роды", () => {
    const лишние = [...БЕЗ_НАПИСАНИЯ].filter((род) => !(род in ГРАММАТИКА.nodes));
    assert.deepEqual(лишние, [], `названы исключениями, а таких родов нет: ${лишние}`);
  });
});

// --------------------------------------------------------------------------
// договор сам с собой и с компилятором
// --------------------------------------------------------------------------
describe("договор", () => {
  for (const род of Object.keys(ГРАММАТИКА.nodes).sort()) {
    test(`образец узнаётся своим родом: ${род}`, () => {
      const образец = ГРАММАТИКА.nodes[род].sample;
      assert.equal(узнать(образец), род);
      assert.deepEqual(беды(образец), []);
    });
  }

  for (const слово of ГРАММАТИКА.nodes.arith.keys.op.one_of) {
    test(`компилятор знает слово арифметики: ${слово}`, () => {
      // Слово языка без перевода в SQL -- отказ уже на устройстве, у человека.
      compileExpr({ op: слово, args: [1, 2, 3] }, { table: "t" });
    });
  }

  const ИСПОРЧЕННОЕ = [
    { field: "тег" },                       // запись компилятора, не языка
    { op: "не-слово-языка", args: [1] },    // слова такого нет
    { op: "=", l: { r: "тег" } },           // сравнение без правой стороны
    { r: 3 },                               // имя не строкой
    { agg: "count" },                       // свёртка без модели
    { unset: true, r: "тег" },              // два узла в одном
  ];
  for (const испорченное of ИСПОРЧЕННОЕ) {
    test(`сторож умеет отказать: ${JSON.stringify(испорченное)}`, () => {
      // Сторож, который не ругается ни на что, не сторожит ничего.
      assert.ok(беды(испорченное).length);
    });
  }
});

// --------------------------------------------------------------------------
// библиотека объявления против образцов
// --------------------------------------------------------------------------
test("привязка на JavaScript собирает те же узлы", () => {
  const ответ = JSON.parse(execFileSync("node", [ДРАЙВЕР], {
    input: JSON.stringify(ГРАММАТИКА), encoding: "utf8",
  }));

  assert.deepEqual(ответ.refused, {}, "конструктор есть, а узел не собрался");
  for (const [род, собранное] of Object.entries(ответ.built)) {
    assert.deepEqual(беды(собранное), []);
    assert.deepEqual(собранное, ГРАММАТИКА.nodes[род].sample,
                     `узел ${род} на JavaScript записан иначе, чем в грамматике`);
  }
  // Не «сколько-нибудь», а поимённо: драйвер, разучившийся собирать, иначе
  // прошёл бы молча. Список короткий не по бедности: условие пишется строкой,
  // и своих сравнений нет ни у одной привязки.
  for (const род of ["record_ref", "view_ref", "item_ref", "order", "text"]) {
    assert.ok(род in ответ.built, `драйвер разучился собирать ${род}`);
  }
  assert.ok(ответ.unknown.refused,
            "чужой узел обязан отказать вслух: молча доехавшее не то условие "
            + `показывает не те записи, а тут вышло ${JSON.stringify(ответ.unknown.value)}`);
});
