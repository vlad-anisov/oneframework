test("рендереру дают ответы и никогда -- вопросы", async () => {
  // `visible=` и `enabled=` -- выражения в документе и «да»/«нет» в дереве.
  // Ровно та граница, ради которой вид разделён надвое: в документе условие
  // обязано сохраниться целиком, иначе шаблон, разложенный на две машины,
  // значит на них разное; в дереве от него обязан остаться ответ, иначе
  // рендереру пришлось бы уметь вычислять домены -- и он бы вычислял их иначе.
  for (const узел of узлы((await рантайм()).snapshot())) {
    for (const ключ of ["visible", "enabled"]) {
      if (!(ключ in узел)) continue;
      // Внутри строки списка ответ у каждой записи свой, и живёт он в её
      // векторе: узел называет гнездо, а на месте самого ответа стоит `null`.
      // Выражения не остаётся и там.
      if ((узел.bind || {})[ключ] !== undefined && (узел.bind || {})[ключ] !== null) {
        assert.equal(узел[ключ], null, `${узел.type}.${ключ} и связано, и отвечено сразу`);
        continue;
      }
      assert.equal(typeof узел[ключ], "boolean",
                   `${узел.type}.${ключ} приехало выражением: ${JSON.stringify(узел[ключ])}`);
    }
  }
});

