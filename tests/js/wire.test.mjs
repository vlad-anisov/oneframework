/**
 * Обработчик, которого не зовёт никто.
 *
 * `on_flush` в рантайме есть, но кадра `{"type": "flush"}` не шлёт никто -- ни
 * рендерер, ни хост, ни одна проверка. Хост, которому нужна запись на диск,
 * зовёт базу напрямую (`web/src/runtime/worker.js::flush`), потому что базой он
 * и владеет; путь через событие -- вторая копия того же умения, и она не
 * исполняется ни разу. Правильный конец у неё один -- удаление. Пока этого не
 * сделали, имя стоит здесь: сверка точная, поэтому удаление уронит проверку и
 * заставит убрать заодно и эту строку.
 */
const НЕЗВАННЫЕ_ОБРАБОТЧИКИ = ["flush"];

test("рантайм отвечает ровно на объявленные действия", () => {
  // Обратная сторона проверки «объявлено, но не шлётся»: там ловится обещание
  // без исполнителя, здесь -- исполнитель без обещания. Второе тише: такой
  // обработчик не падает, не мешает и не зовётся, он просто лежит, и рядом с
  // ним лежит уверенность, что провод описан целиком.
  assert.deepEqual(Object.keys(читаемое(RUNTIME)).sort(),
                   [...Object.keys(SCHEMA.actions), ...НЕЗВАННЫЕ_ОБРАБОТЧИКИ].sort());
});

test("документ называет те же действия, что схема", () => {
  // Именно там `set_search` числился с ключом `text`, и там же жили `create` и
  // `refresh` -- действия, которых не шлёт рендерер и не знает ни один рантайм.
  // Документ, который никто не сверяет, врёт так же молча, как схема.
  const таблица = действияДокумента();
  assert.deepEqual(Object.keys(таблица).sort(), Object.keys(SCHEMA.actions).sort());
  for (const [имя, spec] of Object.entries(SCHEMA.actions)) {
    assert.deepEqual(таблица[имя], [spec.required, spec.optional || []],
                     `${имя}: документ и схема разошлись`);
  }
});

test("описанное и исполняемое совпадают", () => {
  // Читается весь рендерер, а не один файл, и читается перечислением каталога,
  // а не списком имён. Раньше здесь стоял `renderer.js` в единственном числе, и
  // проверка держалась на том, что все отправки лежат в нём одном -- допущение,
  // переставшее быть верным, как только рендерер начал переезжать по частям.
  // Потом здесь появился список из трёх имён, и он устарел на следующем же
  // шаге. Тест при этом падал бы не на настоящей потере действия, а на
  // переименовании файла: ложная тревога, из-за которой ему поверят меньше.
  const текст = рендерер();
  for (const [имя, spec] of Object.entries(SCHEMA.actions)) {
    const шлётся = текст.includes(`type: "${имя}"`);
    // `sender` разделяет провод надвое: почти всё шлёт рендерер, а `probe` --
    // хост. Проверяется поэтому не «шлётся», а «шлётся тем, кто назван»: иначе
    // пометка была бы словом без последствий, и действие рендерера, названное
    // хостовым, выпало бы из проверки целиком.
    if (spec.sender === "renderer") assert.ok(шлётся, `${имя} описан, но не отправляется`);
    else assert.ok(!шлётся, `${имя} назван хостовым, а шлёт его рендерер`);
  }
});

test("запись проезжает провод в обе стороны", async () => {
  // Единственное действие, меняющее данные, -- через связанную строку, потому
  // что именно она у рендерера в руках, когда человек нажал: узел приходит из
  // `list.row`, ключ записи и значение -- из её вектора.
  const rt = await рантайм();
  const список = [...узлы(rt.snapshot())].find((н) => н.type === "list");
  const строка = список.rows[0];
  const гнездо = (узел, ключ) => {
    const н = (узел.bind || {})[ключ];
    return н === undefined || н === null ? узел[ключ] : строка.v[н];
  };
  const поле = [...обойти(список)].find(
    (н) => н.type === "field" && н.scope === "record" && н.ftype === "boolean");
  const значение = гнездо(поле, "value");
  rt.dispatch({ type: "write", model: список.model, record_id: строка.id,
                values: { [поле.name]: !значение } });
  assert.deepEqual(нет(поле, SCHEMA.nodes.field.required), []);
  // Что запись доехала, видно по списку: под отбором «Осталось» выполненной
  // строки больше нет. Спрашивается последствие, а не «не упало»: молчаливо
  // проглоченная запись выглядела бы точно так же успешной.
  assert.equal(значение, false, "образец рассчитан на невыполненную строку");
  const после = [...узлы(rt.snapshot())].find((н) => н.type === "list");
  assert.equal(после.state.filter, 0, "отбор сменился -- проверка мерит не то");
  assert.ok(!после.rows.some((с) => с.id === строка.id),
            "строку отметили выполненной, а она осталась среди оставшихся");
});

