/**
 * Провод между языком приложения и рендерером.
 *
 * Рендерер не знает про язык приложения ничего -- он получает снимок и шлёт
 * действия. Эта граница -- единственное, что пришлось бы написать заново
 * другому языку, поэтому она закреплена здесь, а не подразумевается кодом,
 * который её случайно производит.
 *
 * Три правила держат весь файл вместе:
 *
 * * каждый узел, который рендерер может получить, перечислен -- с ключами,
 *   которые он обязан нести;
 * * каждое действие, которое рендерер может отправить, перечислено -- с
 *   ключами, которые оно обязано нести;
 * * действие без обязательного ключа обязано отказать, а не догадаться.
 *
 * Добавить тип узла или действие, не поправив `protocol/wire.json`, здесь
 * падает -- в этом и смысл: схема и есть договор, а не описание к нему.
 *
 * Третье правило -- то, чего разделу `actions` не хватало дольше всего. Ключи
 * он перечислял, но перечисление никто не сверял ни с отправителем, ни с
 * обработчиком, ни с документом, и разошлось оно ровно так, как расходится
 * непроверяемая запись: `set_search` был объявлен с ключом `text`, а ехал с
 * `value`. Поэтому каждое действие спрашивается с четырёх сторон -- схема,
 * рендерер, рантайм, `docs/protocol.md` -- и вдобавок изъятием ключа: кадр
 * собирается законным и у него отнимают один ключ.
 *
 * Файл назван по имени схемы, которую он сторожит. Имя `test_protocol.py`
 * занято договором о **полях**, и это разные записи: там таблица типов, здесь
 * провод.
 *
 * Как этого файла не стало. Он был написан под именем `test_protocol.py`, а
 * коммит `3776323` записал поверх него другой файл -- 708 строк и 21 теста
 * исчезли, не сказав ни слова ни в сообщении коммита, ни в прогоне: имя занял
 * новый файл, и прогон остался зелёным. `protocol/wire.json` после этого не
 * читал никто, хотя шесть мест утверждали обратное. Мораль записана здесь
 * потому, что стеречь себя файл не умеет: сторож, потерянный вместе с именем,
 * -- единственная поломка, которую не покажет ни один прогон.
 */

