/**
 * Тело объектного литерала, открытого скобкой в позиции `скобка`.
 *
 * Разбор посимвольный, а не выражением: в отправке бывают вложенные объекты
 * (`values: {...}`, `context: {...}`) и строки, и всякий разбор, считающий
 * первую же `}` концом, прочитал бы меньше ключей, чем едет. Меньше -- значит
 * молча пропустил бы ровно тот ключ, ради которого всё это.
 */
function литерал(текст, скобка) {
  let глубина = 0, кавычка = null, i = скобка;
  while (i < текст.length) {
    const с = текст[i];
    if (кавычка) {
      if (с === "\\") { i += 2; continue; }
      if (с === кавычка) кавычка = null;
    } else if ("\"'`".includes(с)) кавычка = с;
    else if ("{[(".includes(с)) глубина += 1;
    else if ("}])".includes(с)) {
      глубина -= 1;
      if (глубина === 0) return текст.slice(скобка + 1, i);
    }
    i += 1;
  }
  throw new Error("незакрытый литерал в рендерере");
}

/**
 * Имена ключей верхнего уровня -- короткая запись в том числе.
 *
 * `{ type: "set_search", list_id: listId, value }` -- три ключа, и у третьего
 * имя со значением записаны одним словом. Пропусти короткую запись -- и самый
 * интересный ключ провода (`value`) в проверку бы не попал.
 */
function ключи(тело) {
  const части = [];
  let глубина = 0, кавычка = null, часть = "";
  for (const с of тело) {
    if (кавычка) {
      часть += с;
      if (с === кавычка) кавычка = null;
      continue;
    }
    if ("\"'`".includes(с)) кавычка = с;
    else if ("{[(".includes(с)) глубина += 1;
    else if ("}])".includes(с)) глубина -= 1;
    else if (с === "," && глубина === 0) { части.push(часть); часть = ""; continue; }
    часть += с;
  }
  части.push(часть);
  return части.filter((к) => к.trim()).map((к) => к.split(":")[0].trim());
}

/**
 * Каждая отправка действия рендерером -- именем и набором ключей.
 *
 * Отправка узнаётся по `type: "имя"`, и читается весь литерал, а не одно имя.
 * Имена, не объявленные действиями, пропускаются нарочно -- `type:` в
 * рендерере называет ещё и вид поля ввода (`<input type="text">`) и вид листа
 * Framework7, а это не провод.
 */
function отправки() {
  const текст = рендерер();
  const найдено = [];
  for (const м of текст.matchAll(/type:\s*"([a-z_]+)"/g)) {
    const имя = м[1];
    if (!(имя in SCHEMA.actions)) continue;
    let начало = м.index - 1;
    while (начало >= 0 && " \t\r\n".includes(текст[начало])) начало -= 1;
    assert.equal(текст[начало], "{", `${имя}: отправка не литералом`);
    найдено.push([имя, new Set(ключи(литерал(текст, начало)).filter((к) => к !== "type"))]);
  }
  assert.ok(найдено.length, "в рендерере не нашлось ни одной отправки");
  return найдено;
}

/**
 * Ключи, которые обработчики рантайма достают из события.
 *
 * Читается тело каждого `on_*`, и только верхний уровень: `ev.screen_id`
 * внутри `action` -- ключ *контекста*, а не кадра, и договор о нём не говорит.
 */
function читаемое(файл) {
  const текст = readFileSync(файл, "utf8");
  // Ключевые слова стоят в тексте на том же отступе, что и методы класса, и
  // приняв `if (` за начало следующего метода, разбор оборвал бы тело
  // предыдущего на середине -- то есть недосчитал бы прочитанных ключей.
  const слова = new Set(["if", "for", "while", "switch", "catch", "return", "function"]);
  const начала = [...текст.matchAll(/\n {2}([A-Za-z_$][\w$]*)\(/g)]
    .filter((м) => !слова.has(м[1]))
    .map((м) => [м.index, м[1]]);
  const наружу = {};
  начала.forEach(([где, имя], и) => {
    if (!имя.startsWith("on_")) return;
    const конец = и + 1 < начала.length ? начала[и + 1][0] : текст.length;
    наружу[имя.slice(3)] =
      new Set([...текст.slice(где, конец).matchAll(/\bev\.([a-z_]+)/g)].map((м) => м[1]));
  });
  assert.ok(Object.keys(наружу).length, `в ${path.basename(файл)} не нашлось обработчиков`);
  return наружу;
}

const документ = () => readFileSync(path.join(ROOT, "docs", "protocol.md"), "utf8");

/**
 * Таблица действий из `docs/protocol.md`, разобранная как схема.
 *
 * Ключ со знаком `?` -- необязательный. Разбирается затем, что именно в этой
 * таблице `set_search` годами звался `text`: документ, который никто не
 * сверяет, расходится с кодом ровно так же, как схема, -- и так же молча.
 */
function действияДокумента() {
  const раздел = документ().split("## Вверх: действия")[1].split("\n## ")[0];
  const таблица = {};
  for (const строка of раздел.split("\n")) {
    const ячейки = строка.trim().replace(/^\||\|$/g, "").split("|").map((я) => я.trim());
    if (ячейки.length !== 3 || !ячейки[0].startsWith("`")) continue;
    const кк = ячейки[1] === "—" ? [] : ячейки[1].split(",").map((к) => к.replace(/`/g, "").trim());
    таблица[ячейки[0].replace(/`/g, "")] = [
      кк.filter((к) => !к.endsWith("?")),
      кк.filter((к) => к.endsWith("?")).map((к) => к.slice(0, -1)),
    ];
  }
  assert.ok(Object.keys(таблица).length, "таблица действий в документе не найдена");
  return таблица;
}

/**
 * Ключи кадра из таблицы в `docs/protocol.md`. `?` -- необязательный.
 *
 * Описаний у кадра два -- схема и эта таблица, -- и то из них, которое никто
 * не читал, разошлось: `dismiss` решает в рендерере «закрыть» против «назад»,
 * `target` -- лист против страницы, `draft` -- вид карточки, и ни одного из
 * трёх в таблице не стояло. Читающий её писал бы третий рантайм без них.
 */
function ключиКадраДокумента() {
  const раздел = документ().split("### Кадр")[1].split("\n### ")[0];
  const набор = new Set();
  for (const строка of раздел.split("\n")) {
    const ячейки = строка.trim().replace(/^\||\|$/g, "").split("|").map((я) => я.trim());
    if (ячейки.length !== 2 || !ячейки[0].startsWith("`")) continue;
    for (const к of ячейки[0].split(",")) набор.add(к.replace(/`/g, "").trim());
  }
  assert.ok(набор.size, "таблица кадра в документе не найдена");
  return набор;
}

