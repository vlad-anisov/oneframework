/**
 * Каждый типизованный узел дерева, включая вместилища.
 *
 * `rows` списка -- не узлы: они несут ключ записи и её значения, а не `type`,
 * -- и достаются отдельно. Узлы, которым эти значения принадлежат, стоят один
 * раз, в `list.row`, и обходятся здесь. Всё прочее, что висит на узле, а не
 * стоит среди детей, обходится тоже: меню списка, части заголовка вкладки и её
 * плавающая кнопка -- узлы, которые рендерер рисует, и договор, их
 * пропустивший, был бы договором с дырами в самых расходящихся местах.
 */
function* обойти(узел) {
  yield узел;
  for (const ключ of ["children", "title"]) {
    for (const дитя of узел[ключ] || []) yield* обойти(дитя);
  }
  for (const ключ of ["menu", "fab"]) {
    if (узел[ключ]) yield* обойти(узел[ключ]);
  }
  const шаблон = узел.row;
  if (шаблон) {
    for (const ключ of ["children", "cells"]) {
      for (const дитя of шаблон[ключ] || []) yield* обойти(дитя);
    }
  }
}

function* узлы(снимок) {
  for (const стек of Object.values(снимок.stacks)) {
    for (const кадр of стек) {
      for (const дитя of кадр.children || []) yield* обойти(дитя);
    }
  }
}

