/**
 * Весь рендерер одной строкой -- перечислением каталога, а не списком имён.
 *
 * Рендерер -- это `web/src`, кроме `runtime/`: рантайм события принимает, а не
 * отправляет, и попади он сюда, проверка перестала бы отличать отправленное
 * действие от принятого. Каталог перечисляется целиком именно потому, что
 * файлы в нём переименовываются и появляются: список имён устаревает молча.
 */
function рендерер() {
  const корень = path.join(ROOT, "web", "src");
  const файлы = [];
  const обойти = (где) => {
    for (const имя of readdirSync(где).sort()) {
      const п = path.join(где, имя);
      if (statSync(п).isDirectory()) { if (имя !== "runtime") обойти(п); continue; }
      if (имя.endsWith(".js") || имя.endsWith(".jsx")) файлы.push(п);
    }
  };
  обойти(корень);
  assert.ok(файлы.length, "рендерер не найден");
  return файлы.map((п) => readFileSync(п, "utf8")).join("\n");
}

