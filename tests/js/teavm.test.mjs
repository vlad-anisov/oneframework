/**
 * Сборка модуля WebAssembly -- правилами, а не сверкой с питоном.
 *
 * Работу выданного проверяет `tests/e2e/notes-kotlin.spec.js`: жмёт кнопку в
 * собранном приложении и смотрит, посчиталась ли сводка. Сверка двух сборщиков
 * без такой проверки говорила бы лишь, что оба выдали одно; работает ли оно,
 * из неё не следовало.
 *
 * Здесь остались правила, которые сквозной сюитой не увидеть: что считается
 * успехом, что входит в отпечаток кэша и как читается объявленная зависимость.
 */

import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import {
  build, библиотека, classpath, home, kotlinCompiler, resolve, удалась,
} from "../../src/build/teavm.mjs";

const времянка = () => mkdtempSync(path.join(tmpdir(), "teavm-"));

/** Без компилятора Kotlin котлиновская половина сюиты спит. */
const безКомпилятора = (() => {
  try { return !kotlinCompiler(); } catch { return true; }
})();

// Пары «код возврата, вывод» и то, что обязано получиться. Средняя -- та самая
// ловушка: TeaVM пишет, что собрал с ошибками, и выходит с нулём. Файл при этом
// есть и не работает.
const ИСХОДЫ = [
  [0, "Output file built successfully", true],
  [0, "Output file built with errors", false],
  [0, "\nbuilt with errors\n", false],
  [1, "Output file built successfully", false],
  [1, "", false],
  [0, "", true],
];

test("сборка с ошибками -- это неудача", () => {
  // Ноль на выходе -- ещё не успех, если TeaVM сказал «с ошибками». Правилом,
  // а не настоящей сборкой: заставить TeaVM выдать такой вывод по заказу не
  // выходит -- отражение и файловую систему он терпит. Один раз он уже отдал
  // нерабочий модуль молча.
  assert.deepEqual(ИСХОДЫ.map(([код, вывод]) => удалась(код, вывод)),
                   ИСХОДЫ.map(([, , ждём]) => ждём));
});

for (const адрес of ["commons-lang3", "org.apache.commons:commons-text",
                     "org.apache.commons:commons-text:1.12.0:лишнее", ""]) {
  test(`огрызок зависимости «${адрес}» отвергнут по имени`, () => {
    // «группа:артефакт:версия» -- и никак иначе. Приняв огрызок молча, сборка
    // полезла бы на Maven по бессмысленному адресу и отказала бы уже сетью,
    // где причины не видно.
    assert.throws(() => resolve([адрес]), /группа:артефакт:версия/);
  });
}

test("пустой список зависимостей -- ни одного обращения наружу", () => {
  assert.deepEqual(resolve([]), []);
});

test("оснастка находится там, где вправду лежит", { skip: безКомпилятора }, () => {
  // У распаковки с сайта jar'ы лежат в `<kotlinc>/lib`, у Homebrew --
  // в `libexec/lib`, а в `bin` стоит обёртка. Считалось, что раскладка одна, и
  // приложение на Kotlin не собиралось на обычной установке под macOS:
  // компилировалось, а при запуске падало на `NoClassDefFoundError`.
  const stdlib = библиотека("kotlin-stdlib.jar");
  assert.ok(statSync(stdlib).isFile(), stdlib);
  assert.ok(stdlib.endsWith("kotlin-stdlib.jar"), stdlib);
  // Кэш один на все запуски: скачивать девять артефактов заново на каждой
  // сборке незачем.
  assert.ok(classpath(home()).split(home()).length - 1 >= 9, classpath(home()));
});

// У Kotlin имя файла становится именем класса: файл с функцией верхнего уровня
// даёт класс по своему имени. Значит один и тот же текст под разными именами --
// **разные** модули.
const ВЕРХНИЙ_УРОВЕНЬ = `package oneframework.generated

fun сложить(a: Int, b: Int): Int = a + b

object EntryKt {
    @JvmStatic
    fun main(args: Array<String>) {
        println(сложить(2, 3))
    }
}
`;

/**
 * Собрать и вернуть отметки кэша вместе со временем правки модуля: по нему
 * видно, была ли пересборка. Отметка одна и та же и когда пересобрали, и когда
 * взяли из кэша, поэтому её одной мало.
 */
function собрать(источник, куда) {
  build([источник], куда, "Проба", "oneframework.generated.EntryKt");
  const лежит = readdirSync(куда);
  return {
    метки: лежит.filter((и) => и.startsWith(".")).sort(),
    правлен: лежит.filter((и) => и.endsWith(".wasm"))
.map((и) => statSync(path.join(куда, и)).mtimeMs),
  };
}

test("отпечаток кэша считает имя файла", { skip: безКомпилятора }, () => {
  // Переименование исходника обязано пересобрать модуль -- иначе кэш отдаст
  // классы под старым именем, и запуск не найдёт главного: ровно это однажды и
  // случилось. Отпечаток берётся с содержимого, и без имени два разных модуля
  // выглядят для него одинаково.
  const где = времянка();
  const куда = path.join(где, "модуль");
  const метки = ["Один.kt", "Два.kt"].map((имя) => {
    const источник = path.join(где, имя);
    writeFileSync(источник, ВЕРХНИЙ_УРОВЕНЬ, "utf8");
    return собрать(источник, куда).метки;
  });
  assert.notDeepEqual(метки[0], метки[1],
                      `та же отметка кэша под другим именем -- ${метки[0]}`);
});

test("тот же исходник не пересобирается", { skip: безКомпилятора }, () => {
  // Смотрится **время правки** модуля, а не отметка: отметка одинакова и когда
  // пересобрали, и когда взяли из кэша, и на ней снятый кэш остаётся
  // незамеченным -- замерено. Пересборка Kotlin с TeaVM стоит секунды, и
  // платить их на каждой сборке впустую нельзя.
  const где = времянка();
  const куда = path.join(где, "модуль");
  const источник = path.join(где, "Один.kt");
  writeFileSync(источник, ВЕРХНИЙ_УРОВЕНЬ, "utf8");
  const первый = собрать(источник, куда);
  const второй = собрать(источник, куда);
  assert.ok(первый.метки.length);
  assert.deepEqual(первый.метки, второй.метки);
  assert.ok(первый.правлен.length);
  assert.deepEqual(первый.правлен, второй.правлен,
                   `модуль пересобран, хотя исходник тот же: ${первый.правлен}`);
});
