/**
 * Каноническая запись: одна реализация и внешний судья.
 *
 * Отпечатки считает та сторона, что пишет базу, и судья ей -- не вторая
 * копия, а **сам JavaScript**: правило печати чисел взято у ECMAScript,
 * значит эталон для него `String(число)`, а не наше представление о нём.
 *
 * Модуль ввозится прямо, без запуска процесса на каждую пробу и разбора JSON
 * туда-обратно.
 *
 * `tests/parity/canon_driver.mjs` при этом остался: его зовёт сверка трёх
 * языков (`tests/test_three_languages.py`), а ей питон нужен по существу --
 * она сравнивает документы, напечатанные тремя привязками, и одна из них
 * питоновская.
 */

import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { canonical, fingerprint } from "../../src/runtime/canon.js";

describe("каноническая запись", () => {
  it("порядок ключей -- по кодовым точкам, а не по единицам UTF-16", () => {
    // Различает их только ключ вне основной плоскости. `Array.sort` без
    // сравнителя даёт на такой паре **обратный** порядок, и прежде это
    // ловила только сверка с питоном.
    assert.equal(canonical({ b: 1, a: 2 }), '{"a":2,"b":1}');
    assert.equal(canonical({ "\u{1d11e}": 1, z: 2 }), '{"z":2,"\u{1d11e}":1}');
    assert.equal(canonical({ "￿": "bmp", "\u{1d11e}": "astral" }),
                 '{"￿":"bmp","\u{1d11e}":"astral"}');
  });

  it("печать чисел -- та же, что у String(число): это правило ECMAScript", () => {
    assert.equal(canonical({ x: 3.0 }), '{"x":3}');
    assert.equal(canonical({ x: -0.0 }), '{"x":0}');
    assert.equal(canonical({ x: 1e16 }), '{"x":10000000000000000}');
    assert.equal(canonical({ x: 1e21 }), '{"x":1e+21}');
    assert.equal(canonical({ x: 1e-5 }), '{"x":0.00001}');
    assert.equal(canonical({ x: 1e-7 }), '{"x":1e-7}');
  });

  it("кавычка, слеш, перевод строки и табуляция -- обычным экранированием", () => {
    assert.equal(canonical({ esc: 'a"b\\c\nd\te' }), '{"esc":"a\\"b\\\\c\\nd\\te"}');
  });

  it("документ, который нельзя записать, не получает имени", () => {
    // Получи он отпечаток -- уехал бы обменом, и разобрать его на той стороне
    // было бы нечем.
    for (const [имя, значение] of [["бесконечность", Infinity],
                                   ["минусбесконечность", -Infinity],
                                   ["ненеЧисло", NaN]]) {
      assert.throws(() => canonical({ x: значение }),
                    (о) => /бесконечност|nan/i.test(о.message),
                    `${имя}: записалось`);
    }
  });

  it("отпечаток -- шестнадцать шестнадцатеричных знаков", () => {
    const fp = fingerprint({ a: 1 });
    assert.equal(fp.length, 16);
    assert.match(fp, /^[0-9a-f]{16}$/);
  });

  it("разные документы -- разные имена", () => {
    // Пустой список и пустая карта -- разные документы.
    assert.notEqual(fingerprint([]), fingerprint({}));
  });
});

describe("судья: сам JavaScript", () => {
  it("печать числа совпадает со String(число) на тысяче случайных", () => {
    // Краевые случаи выбраны руками выше; здесь тысяча двойных, каких руками
    // не придумать. Своя случайность, а не `Math.random`: прогон обязан
    // повторяться, иначе упавшую проверку не воспроизвести.
    let семя = 20260821;
    const дальше = () => {
      семя = (семя * 1103515245 + 12345) % 2147483648;
      return семя / 2147483648;
    };
    const числа = [];
    for (let i = 0; i < 500; i += 1) числа.push((дальше() * 2 - 1) * 1e6);
    for (let i = 0; i < 500; i += 1) числа.push((дальше() * 2 - 1) * 1e-6);

    for (const ч of числа) {
      assert.equal(canonical({ x: ч }), `{"x":${String(ч)}}`, `число ${ч}`);
    }
  });
});
