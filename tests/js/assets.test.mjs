/**
 * Значки и адрес обмена -- правилами, а не сверкой с питоном.
 *
 * Значок проверяется не «похож ли», а разбором: заголовок PNG, размеры, тип
 * цвета, и то, что галочка вправду нарисована. Файл уедет на устройство, и
 * «похожая картинка» тут не ответ.
 */

import test from "node:test";
import assert from "node:assert/strict";
import { crc32, inflateSync } from "node:zlib";

import { iconPixels, png, syncAddress } from "../../src/build/assets.mjs";

/** Свой разбор PNG, чтобы не тащить зависимость ради проверки. */
function разобрать(байты) {
  assert.deepEqual([...байты.subarray(0, 8)], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a],
                   "это не PNG");
  const куски = new Map();
  for (let i = 8; i < байты.length;) {
    const длина = байты.readUInt32BE(i);
    const тег = байты.subarray(i + 4, i + 8).toString("latin1");
    const данные = байты.subarray(i + 8, i + 8 + длина);
    assert.equal(байты.readUInt32BE(i + 8 + длина) >>> 0,
                 crc32(Buffer.concat([Buffer.from(тег, "latin1"), данные])) >>> 0,
                 `CRC не сошлась у ${тег}`);
    куски.set(тег, данные);
    i += 12 + длина;
  }
  const шапка = куски.get("IHDR");
  const [ширина, высота] = [шапка.readUInt32BE(0), шапка.readUInt32BE(4)];
  const сырое = inflateSync(куски.get("IDAT"));
  const строка = ширина * 4 + 1;
  const точки = [];
  for (let y = 0; y < высота; y += 1) {
    assert.equal(сырое[y * строка], 0, "фильтр строки обязан быть «никакой»");
    точки.push(Array.from({ length: ширина }, (_, x) =>
      [...сырое.subarray(y * строка + 1 + x * 4, y * строка + 5 + x * 4)]));
  }
  return { ширина, высота, глубина: шапка[8], цвет: шапка[9], точки };
}

const значок = (размер) => Buffer.from(png(размер, iconPixels(размер)));

for (const размер of [192, 512]) {
  test(`значок ${размер} -- настоящий PNG с альфой`, () => {
    const п = разобрать(значок(размер));
    assert.deepEqual([п.ширина, п.высота], [размер, размер]);
    assert.equal(п.глубина, 8);
    assert.equal(п.цвет, 6, "тип 6 -- RGBA; без альфы значок потеряет маску");
  });

  test(`на значке ${размер} вправду нарисована галочка`, () => {
    // Пустая заливка тоже была бы правильным PNG нужного размера, и проверка
    // заголовков её бы пропустила -- на устройстве оказался бы одноцветный
    // квадрат.
    const { точки } = разобрать(значок(размер));
    const фон = [103, 80, 164, 255];
    const все = точки.flat();
    const белых = все.filter((т) => т[0] === 255 && т[1] === 255 && т[2] === 255).length;
    const иных = все.filter((т) => фон.some((з, i) => з !== т[i])).length;
    assert.deepEqual(точки[0][0], фон, "угол обязан остаться фоном");
    assert.ok(белых > размер, "белого слишком мало для галочки");
    // Сглаженные края -- не фон и не чистый белый: без них галочка ступенчатая.
    assert.ok(иных > белых, "краёв нет -- сглаживание пропало");
    // Тип цвета 6 значит, что альфа читается: прозрачная галочка на прозрачных
    // краях -- это правильный PNG, на котором ничего не видно.
    assert.ok(все.every((т) => т[3] === 255), "точка стала прозрачной");
  });
}

test("значок один и тот же при каждом запуске", () => {
  // Изменившийся байт значка -- изменившийся отпечаток офлайн-кэша, то есть
  // перезакачка всего приложения на каждой сборке.
  assert.deepEqual(значок(192), значок(192));
});

// Пусто и «off» значат одно -- обмена нет. Отсутствие переменной значит другое:
// оставить то, что объявило приложение. Спутать их -- собрать неотключаемый
// обмен либо молча выключить объявленный.
for (const значение of ["off", "OFF", "", "0", "none", "  "]) {
  test(`адрес «${значение}» выключает обмен`, () => {
    assert.equal(syncAddress({ sync: "объявленный" }, { PYAPP_SYNC_URL: значение }).sync, false);
  });
}

for (const [значение, ждём] of [["https://terminal.anisov.by", "https://terminal.anisov.by"],
                                ["  https://x  ", "https://x"]]) {
  test(`адрес «${значение}» замещает объявленный, обрезанный`, () => {
    assert.equal(syncAddress({ sync: "объявленный" }, { PYAPP_SYNC_URL: значение }).sync, ждём);
  });
}

test("переменной нет -- объявленный адрес не тронут", () => {
  // Это не то же, что «обмена нет».
  const мета = { title: "T", sync: "объявленный" };
  assert.deepEqual(syncAddress(мета, {}), мета);
});
