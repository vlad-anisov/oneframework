/**
 * Часы устройства: отметка порядка, по которой решается спор при слиянии.
 *
 * Сценарий лежит рядом данными (`данные/hlc.json`), а не собран здесь кодом, и
 * это не про опрятность. Ожидания в нём -- **побайтные отметки**, посчитанные
 * формулой формата, а не вызовом той реализации, которую проверяют: спроси мы
 * их у неё, проверка сравнивала бы её с собой. Формула записана в питоновской
 * половине (`tests/together/test_js_clock.py`, функция `at`), и оттуда же таблицы
 * выгружены -- один сценарий на оба языка.
 *
 * Одиннадцать шагов и четыре перезапуска: часы стоят, часы перевели назад,
 * приехала отметка из будущего, кончился счётчик. Разойдись хоть один байт --
 * разошлись бы и споры при слиянии, а увидеть это можно только по чужой жалобе.
 */

import test, { before } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { Clock, ZERO, check, nodeId, parse }
  from "../../src/runtime/hlc.js";

const ЗДЕСЬ = path.dirname(fileURLToPath(import.meta.url));
const д = JSON.parse(readFileSync(path.join(ЗДЕСЬ, "данные", "hlc.json"), "utf8"));
const ОТМЕТКА = new RegExp(д.STAMP);

/** Отметка формулой -- та же спецификация формата, что у питоновской половины. */
function отметка(ms, счётчик = 0, узел = "bbbbbbbb") {
  const t = new Date(ms).toISOString().slice(0, 19);
  const мс = String(ms % 1000).padStart(3, "0");
  return `${t}.${мс}Z-${счётчик.toString(16).padStart(4, "0")}-${узел}`;
}

/** Проиграть шаги на часах с заданной сохранённой отметкой. */
function сыграть(last, шаги) {
  let шаг = 0;
  const часы = new Clock({ node: д.NODE, last, now: () => шаги[шаг++][1] });
  return шаги.map(([что]) => (что === "tick"
    ? часы.tick()
    : часы.receive(что.slice("receive:".length))));
}

const отказ = (вызов) => { try { вызов(); } catch (б) { return б.message; } return null; };
const стенные = () => д.BASE;

let ч = null;

before(() => {
  ч = {
    played: сыграть(null, д.STEPS),
    restarts: д.RESTARTS.map(([last, шаги]) => сыграть(last, шаги)),
    parsed: д.STAMPS.map(parse),
    node: nodeId(),
    fresh: new Clock({}).tick(),
    wire: д.WIRE.map((с) => отказ(() => check(с, стенные))),
    fromTheWire: отказ(() => new Clock({ node: д.NODE, now: стенные }).receive(д.FAR)),
    // Часы после отказа обязаны остаться рабочими: отказ не смеет бросить их на
    // полпути -- тогда устройство перестало бы стамповать вовсе.
    afterRefusal: (() => {
      const часы = new Clock({ node: д.NODE, now: стенные });
      const было = часы.tick();
      отказ(() => часы.receive(д.FAR));
      return { before: было, after: часы.tick() };
    })(),
    ofItsOwn: отказ(() => new Clock({ node: д.NODE, last: д.FAR, now: стенные }).tick()),
    beyondTheCalendar: д.BEYOND.map((ms) => отказ(() => {
      const часы = new Clock({ node: д.NODE, now: стенные });
      часы.ms = ms;
      return часы.stamp();
    })),
  };
});

test("сценарий штампует те самые байты", () => {
  assert.equal(ZERO, д.ZERO);
  assert.deepEqual(ч.played, д["СЫГРАНО"]);
  assert.deepEqual(ч.restarts, д["ПЕРЕЗАПУСКИ"]);
});

test("отметка разбирается на три части, которые обещает", () => {
  // Время, счётчик, узел -- либо пусто, где отметки нет.
  assert.deepEqual(ч.parsed, д["РАЗОБРАНО"]);
});

test("свежая отметка той формы, что обещает", () => {
  assert.match(ч.fresh, ОТМЕТКА);
  assert.match(ч.node, /^[0-9a-f]{8}$/);
  assert.equal(ч.fresh.length, д.ZERO.length, "ширина частей та же, что у нуля");
});

test("приём подтягивает часы", () => {
  // Ровно это и делает часы логическими: отстающее устройство после первого же
  // обмена перестаёт выдавать отметки из прошлого.
  const впереди = отметка(д.BASE + 60_000);
  const с = ч.played;
  assert.ok(с[5] > впереди, "ответ на чужую отметку её не обогнал");
  assert.ok(с[6] > с[5], "следующий свой шаг откатился");
  for (let i = 1; i < с.length; i += 1) assert.ok(с[i] > с[i - 1], `${i}: ${с[i-1]} -> ${с[i]}`);
});

test("отметка сортируется как обычная строка", () => {
  // Ради этого части и держат фиксированную ширину.
  assert.ok(д.ZERO < отметка(0));
  assert.ok(отметка(0) < отметка(д.BASE));
  assert.ok(отметка(д.BASE) < отметка(д.BASE, 1));
  assert.ok(отметка(д.BASE, 1) < отметка(д.BASE + 1));
  assert.deepEqual([отметка(д.BASE, 16), отметка(д.BASE, 2)].sort(),
                   [отметка(д.BASE, 2), отметка(д.BASE, 16)]);
});

test("ни один шаг сценария не расширяет счётчик", () => {
  // Ширина частей -- не пожелание, и проверять её надо на каждом шаге.
  // Ограничение счётчика стояло в `tick` и не стояло в `receive`, а чужой
  // счётчик приезжает из провода: `ffff` + 1 давал `10000`, пять знаков. Такая
  // отметка сортируется не позже всех, а **раньше**, и спор решается наоборот.
  //
  // Сценарий его уже проходил, а смотрели только на то, что отметки растут, --
  // и растут они и с пятизначным счётчиком, потому что дальше сдвинулось время.
  for (const набор of [ч.played, ...ч.restarts]) {
    for (const с of набор) assert.match(с, ОТМЕТКА);
  }
});

test("отметка из провода не утаскивает часы в будущее", () => {
  // Одна отметка из 2999 года выводила из строя весь парк, и необратимо: часы
  // поднимались до неё, поднятое уходило в `hlc:last` и переживало перезапуск.
  // Отказ громкий -- это цена, названная вслух, а не поправка втихую, которая
  // сделала бы приезжего победителем каждого спора.
  assert.ok(ч.fromTheWire, "отметка из 2999 года принята молча");
  assert.ok(ч.fromTheWire.includes(д.FAR), ч.fromTheWire);
  assert.ok(ч.fromTheWire.includes("стенные часы"), ч.fromTheWire);
  // Часы остались рабочими: отказ не бросил их на полпути и не утащил в
  // будущее вместе с отвергнутой отметкой.
  assert.ok(ч.afterRefusal.after > ч.afterRefusal.before, JSON.stringify(ч.afterRefusal));
  assert.ok(ч.afterRefusal.after < отметка(д.BASE + 86_400_000), JSON.stringify(ч.afterRefusal));
});

test("часы, оставленные в будущем прежней сборкой, говорят это вслух", () => {
  // Предел -- и на свою отметку тоже, иначе он не лечит уже испорченное:
  // `receive` на таком устройстве больше не вызывается, а `tick` травил бы
  // парк, никого ни о чём не спрашивая.
  assert.ok(ч.ofItsOwn, "часы, оставленные в будущем, продолжили штамповать молча");
  assert.ok(ч.ofItsOwn.includes("Сохранённая отметка"), ч.ofItsOwn);
});

test("проверка провода пропускает отметку и ничего кроме", () => {
  // Форма целиком, а не «похоже на дату»: отметка живёт в журнале сервера той
  // самой строкой, какой приехала, и сравнивается с чужими обычным строковым
  // сравнением. Прописные `00FF` встанут раньше строчных `00aa`, пятизначный
  // счётчик -- раньше всех, и спор решится наоборот.
  //
  // Формы, однако, мало. «9999-99-99T99:99:99.999Z» её выдерживает, но времени
  // не называет: предел расхождения читает такую отметку как ноль и пропускает,
  // а в журнале она строкой стоит выше всякой настоящей. «٢٠٢٦-…» -- та же дыра
  // с другого конца: `\d` в питоне ловит цифры любого письма, в JavaScript --
  // только ASCII, и сервер принял бы в журнал отметку, которую каждое
  // устройство потом отвергнет.
  const прошли = ч.wire.map((о) => о === null);
  assert.deepEqual(прошли, [true, true, true, ...Array(д.WIRE.length - 3).fill(false)],
                   JSON.stringify(д.WIRE.map((с, i) => [с, прошли[i]])));
  // ...и отказ объясняет, чего ждали, а не только что не вышло.
  const мусор = ч.wire[д.WIRE.indexOf("мусор")];
  assert.ok(мусор.includes("2026-08-15T09:41:03.118Z-0000-7f3a9c21"), мусор);
});

test("отказ называет оба момента, а не промежуток между ними", () => {
  // Разница в часах округляется вниз, а отказ начинается ровно на сутках: всё
  // от суток до суток с часом читалось бы «обгоняет на 24 ч при пределе в 24 ч»,
  // и это самый частый случай -- честно уплывшие часы, а не отметка из 2999
  // года. Названные моменты не округляются: человек видит время отметки, время
  // своих часов и решает сам.
  const текст = ч.wire[д.WIRE.indexOf(д.NEAR)];
  assert.ok(текст, "отметка за пределом расхождения принята молча");
  assert.ok(текст.includes("2026-08-16T09:41:03.119Z"), текст);   // время отметки
  assert.ok(текст.includes("2026-08-15T09:41:03.118Z"), текст);   // ...и стенных часов
  // ...а на другом конце -- 2999 год словами отметки, а не в 8523710 ч.
  assert.ok(ч.fromTheWire.includes("2999-01-01T00:00:00.000Z"), ч.fromTheWire);
});

test("время, которого отметка не вмещает, -- отказ, а не поломка", () => {
  // `toISOString` от 10000 года возвращает `+010000-01-01T…`, `parse` от такой
  // строки даёт нули -- и устройство переходит к тихому проигрышу каждого спора.
  д.BEYOND.forEach((ms, i) => {
    const о = ч.beyondTheCalendar[i];
    assert.ok(о, `время ${ms} принято молча`);
    assert.ok(о.includes("1970 по 9999"), `${ms}: ${о}`);
  });
});
