"""HTTP сервера обмена на JS: то же поведение, что у питоновского.

Точка обмена по HTTP, предполётный ответ, раздача собранного клиента,
ограждение от обхода каталога и долговечность базы.

Раньше эти правила держались с двух сторон: питоновский сервер и сверка круг в
круг. Оба убраны 20.08.2026 -- вторая реализация всего обмена признана слишком
дорогой. Значит этот файл теперь единственный, кто их держит, и мерить он
обязан не «работает», а **каждое правило поимённо**: сверять стало не с чем.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

from conftest import needs_node

ROOT = Path(__file__).resolve().parents[1]
DRIVER = ROOT / "tests" / "parity" / "http_driver.mjs"

pytestmark = needs_node

_ОТВЕТ = None


def ответ():
    global _ОТВЕТ
    if _ОТВЕТ is None:
        готово = subprocess.run(
            ["node", str(DRIVER)], capture_output=True, text=True,
            encoding="utf-8", cwd=ROOT,
        )
        assert готово.returncode == 0, готово.stderr
        _ОТВЕТ = json.loads(готово.stdout)
    return _ОТВЕТ


def test_the_exchange_point_answers_over_http():
    """Круг обмена доезжает через настоящий POST, а не только вызовом."""
    о = ответ()["обмен"]
    assert о["код"] == 200
    assert о["тело"]["protocol"] == 1
    assert о["тело"].get("error") is None
    assert о["тело"]["cursor"] == 0


def test_a_diverged_schema_comes_back_as_an_answer_not_as_a_failure():
    """Отказ обмена -- это ответ: устройству есть что с ним делать.

    Пустой разрыв связи оно объяснить не может, а отказ со словами -- может.
    """
    о = ответ()["чужаясхема"]
    assert о["код"] == 200
    assert "Схемы разошлись" in о["тело"]["error"]


def test_the_preflight_allows_the_header_the_device_sends():
    """`Authorization` устройство шлёт всегда, когда обмен закрыт ключом.

    Заголовок, не названный в предполётном ответе, браузер не пропускает -- и
    не пропускает молча. С одного источника это не видно вовсе: беда вылезает
    в вебвью Capacitor и в PWA на другом домене.
    """
    о = ответ()["предполёт"]
    assert о["код"] == 204
    разрешено = {ч.strip() for ч in (о["разрешено"] or "").split(",")}
    assert {"Content-Type", "Authorization"} <= разрешено


def test_the_stand_says_out_loud_that_it_is_open():
    """Стенд без ключа обязан говорить это вслух, а не умалчивать."""
    о = ответ()["паспорт"]
    assert о["тело"]["auth"] is False
    assert о["стенд"] == "test; no authentication"
    assert о["источник"] == "*"


def test_the_built_client_is_served():
    assert ответ()["корень"]["код"] == 200
    assert "text/html" in ответ()["корень"]["тип"]
    assert ответ()["файл"]["код"] == 200
    assert "javascript" in ответ()["файл"]["тип"]
    assert ответ()["нетТакого"]["код"] == 404


def test_nothing_outside_the_built_client_is_reachable():
    """Первое из двух дешёвых ограждений: наружу отдаётся только `dist`.

    База сервера лежит рядом с ним, и достать её по HTTP не должно выйти ни
    точкой-точкой, ни ссылкой.
    """
    о = ответ()
    #: Через HTTP -- двумя дорогами: с закодированными точками и сырым запросом,
    #: который node не нормализует.
    assert о["обходКаталога"]["код"] == 404
    assert о["обходСырой"]["код"] == 404
    #: И напрямую у сторожа: `fetch` нормализует `/../` до отправки, и через
    #: него сторож не зовётся вовсе. Первая редакция этой проверки была
    #: зелёной со снятым сторожем -- ловится только так.
    assert о["сторож"]["наружу"] is None
    assert о["сторож"]["вбок"] is None
    assert о["сторож"]["свой"] is True


def test_the_database_survives_a_restart():
    """SQLite под node живёт в памяти, и файл -- это выгрузка байтами.

    Значит долговечность здесь не даётся сама собой, как в OPFS: её надо
    проверять, иначе сервер теряет всё при первом же перезапуске -- молча.
    """
    assert ответ()["послеПерезапуска"] == ["пережило"]


def test_a_write_is_on_disk_before_the_answer():
    """Ответ «принято» -- обещание, и до записи его давать нельзя.

    Устройство, получившее подтверждение, вправе выбросить changeset из своей
    очереди. Скажи сервер «принято» и умри до записи -- правка не существует
    больше нигде.

    До 20.08.2026 сохранение шло по таймеру, и процесс, убитый между тиками,
    терял до секунды чужой работы -- молча. У питоновского сервера такого окна
    нет: там журнал SQLite лежит на диске. Разница в долговечности была бы
    худшим родом разницы -- незаметной.

    Здесь таймер выставлен в час, а сервер бросается без остановки: если
    правка на диске, значит её положил обмен, а не таймер и не выход.
    """
    assert ответ()["безОстановки"] == ["до обмена"]
