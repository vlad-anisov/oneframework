"""Предел шагов у базы устройства: убегающий запрос обязан обрываться.

Без предела неудачное условие по связи вешает приложение наглухо, и снаружи это
выглядит не ошибкой, а «зависло»: жаловаться будет тот, кто формулу не писал и
починить её не может.

Правило было записано дважды -- у питоновской базы (`model/storage.py`) и у
той, что на устройстве. Сторожила его только питоновская. Проверено мутацией
21.08.2026: снятый предел в `db.js` оставлял **всю сюиту зелёной**, то есть
беззащитной была живая половина.

Арифметика проверяется отдельно от обрыва и без часов. До 20.08.2026 счётчик
уменьшался на **вызов** сторожа, а не на шаг: предел был в тысячу раз выше
названного -- 20 миллиардов шагов вместо 20 миллионов, -- и убегающий запрос
резался через 177 секунд. Ровно то «зависло», от которого предел и заводили.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from conftest import needs_node

ROOT = Path(__file__).resolve().parents[1]
DRIVER = ROOT / "tests" / "parity" / "steplimit_driver.mjs"

pytestmark = needs_node

_ОТВЕТ = None


def ответ():
    global _ОТВЕТ
    if _ОТВЕТ is None:
        готово = subprocess.run(["node", str(DRIVER)], capture_output=True,
                                text=True, encoding="utf-8", cwd=str(ROOT))
        assert готово.returncode == 0, готово.stderr
        _ОТВЕТ = json.loads(готово.stdout)
    return _ОТВЕТ


def test_the_limit_is_counted_in_steps_not_in_guard_calls():
    """Предел называется шагами -- значит и считать обязан шаги."""
    б = ответ()["budget"]
    assert б["default"] == б["limit"] // б["tick"]
    assert б["small"] == 2_000, "предел в 2 млн шагов -- это 2 000 вызовов сторожа"


def test_a_runaway_query_is_interrupted(): 
    """И сам обрыв: рекурсия без конца обязана прерваться, а не считать вечно."""
    assert "interrupted" in ответ()["runaway"].lower(), ответ()["runaway"]


def test_the_limit_is_per_query_not_per_session():
    """Остаток счётчика не копится между запросами.

    Копись он -- приложение, поработавшее час, начинало бы обрываться на
    обычных выборках, и виноватым выглядел бы последний запрос, а не все
    прошлые вместе.
    """
    п = ответ()["perQuery"]
    #: Сперва -- что счётчик вообще двигался. На дешёвом запросе сторож не
    #: зовётся ни разу, и проверка прошла бы на реализации без сброса вовсе:
    #: первая редакция была именно такой (поймано мутацией).
    assert п["spent"] > 0, f"счётчик не двигался -- проверять нечего: {п}"
    assert п["afterReset"] == п["budget"], п
