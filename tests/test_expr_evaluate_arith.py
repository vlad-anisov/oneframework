@pytest.fixture(scope="module")
def отборы():
    """Все случаи разом: поднимать sqlite-wasm на каждый -- секунды на пустом."""
    порядок = sorted(СЛУЧАИ)
    ответы = _выборкой([{"node": СЛУЧАИ[и][0], "record": СЛУЧАИ[и][1]} for и in порядок])
    return dict(zip(порядок, ответы))


@pytest.mark.parametrize("имя", sorted(СЛУЧАИ))
def test_the_screen_and_the_query_agree(имя, отборы):
    """Один документ, одна запись -- один ответ."""
    узел, запись = СЛУЧАИ[имя]
    отбор = отборы[имя]
    if "error" in отбор:
        with pytest.raises(Exception, match="division by zero"):
            call("evaluate", узел, запись, {})
        assert "division by zero" in отбор["error"], отбор
        return
    показ = call("evaluate", узел, запись, {})
    assert показ == отбор["ok"], f"{имя}: показ {показ}, отбор {отбор['ok']}"


@pytest.mark.parametrize("слово", ["lower", "upper", "casefold"])
def test_case_folding_is_refused_by_name(слово):
    """Регистр здесь не считается -- и молчит об этом не он, а отказ.

    Ответить «примерно так же» хуже, чем отказать: показ и отбор разошлись бы
    на одной и той же записи, а увидел бы это пользователь.
    """
    from jsrel import ОтказJs

    узел = {"op": "=", "l": {"op": слово, "args": [П("title")]}, "r": "привет"}
    with pytest.raises(ОтказJs, match="не считается"):
        call("evaluate", узел, {"title": "Привет"}, {})


def _выборкой(случаи):
    """Те же выражения, но собранные в SQL и прогнанные настоящей базой.

    Настоящей -- потому что у выборки свои функции с питоновской семантикой:
    округление к чётному и отказ на делении на ноль. Повторить их в проверке
    значило бы завести третью запись тех же правил.
    """
    import json
    import subprocess
    import sys
    from pathlib import Path

    корень = Path(__file__).resolve().parents[1]
    готово = subprocess.run(
        ["node", str(корень / "tests" / "parity" / "evalsql_driver.mjs")],
        input=json.dumps({"cases": случаи}, ensure_ascii=False),
        capture_output=True, text=True, encoding="utf-8", cwd=str(корень))
    assert готово.returncode == 0, готово.stderr
    return json.loads(готово.stdout)
