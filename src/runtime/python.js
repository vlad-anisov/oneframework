/**
 * Настоящий питон на устройстве -- для того, что в SQL не переводится.
 *
 * Язык приложения переводится в запрос, и почти всё, что пишут в формуле,
 * туда переводится. Не переводится словарное: морфология, разбор чужого
 * формата, чтение документа. Для этого здесь поднимается Pyodide -- CPython,
 * собранный в WebAssembly, -- и в нём работают обычные чужие библиотеки.
 *
 * Три решения, каждое со своей ценой:
 *
 * **Лениво.** Рантайм не трогается, пока его не позвали. Замерено: холодный
 * подъём 1--2 с, и платить их на старте приложения значило бы поменять 300 мс
 * запуска на три секунды у всех ради возможности, нужной единицам.
 *
 * **Из своих файлов и без установщика.** `micropip` умеет ставить из сети, но
 * webview у пользователя может быть без неё, а приложение обязано работать
 * офлайн. Да и сам `micropip` приезжает колесом, которого пришлось бы везти
 * вместе с его зависимостями. Колесо -- это zip, а `zipfile` есть в
 * стандартной библиотеке: распаковываем сами, в свою папку на `sys.path`.
 *
 * **Один экземпляр на вкладку.** Второй стоил бы ещё 13 МБ памяти и ничего бы
 * не дал: питон здесь считает, а не хранит.
 */

let подъём = null;

//: Корень приложения. Ставит его `worker.js` при старте -- сам воркер лежит в
//: `/assets/`, и относительный адрес отсюда разрешился бы в `/assets/python/`,
//: которого нет. Замерено на стенде: «Failed to fetch dynamically imported
//: module .../assets/python/pyodide.mjs».
let БАЗА = "/";

/** Сказать, откуда брать рантайм. Зовётся один раз, при старте воркера. */
export function setPythonBase(base) {
  БАЗА = base || "/";
}

const корень = () => `${БАЗА}python/`;

/**
 * Поднять питон, если он ещё не поднят. Повторные вызовы ждут первый.
 *
 * @param {(шаг: string) => void} [прогресс] куда сообщать о ходе: подъём
 *   долгий, и молчащее приложение в это время выглядит зависшим.
 */
export function ensurePython(прогресс = () => {}) {
  if (подъём) return подъём;
  подъём = (async () => {
    прогресс("рантайм");
    const { loadPyodide } = await import(/* @vite-ignore */ `${корень()}pyodide.mjs`);
    const py = await loadPyodide({ indexURL: корень() });

    прогресс("библиотеки");
    const опись = await (await fetch(`${корень()}packages.json`)).json();
    if (опись.wheels?.length) {
      py.FS.mkdirTree("/site");
      for (const имя of опись.wheels) {
        const байты = await (await fetch(`${корень()}wheels/${имя}`)).arrayBuffer();
        py.FS.writeFile(`/site/${имя}`, new Uint8Array(байты));
      }
      py.runPython(`
import sys, zipfile, pathlib
if "/site" not in sys.path:
    sys.path.insert(0, "/site")
for колесо in sorted(pathlib.Path("/site").glob("*.whl")):
    zipfile.ZipFile(колесо).extractall("/site")
    колесо.unlink()
`);
    }
    прогресс("готов");
    return py;
  })();
  return подъём;
}

/**
 * Выполнить объявленный кусок питона на устройстве.
 *
 * `source` -- исходник, приехавший определением, ровно как модели и виды.
 * `entry` -- имя функции в нём. `payload` едет обычным значением: словари и
 * списки переходят границу как есть.
 *
 * Ошибка питона поднимается наружу как есть: подменять её своей значило бы
 * спрятать строку и место, а это единственное, чем ошибка полезна.
 */
export async function runPythonAction(source, entry, payload, прогресс) {
  const py = await ensurePython(прогресс);
  const область = py.toPy({});
  try {
    py.runPython(source, { globals: область });
    const fn = область.get(entry);
    if (!fn) {
      throw new Error(`в объявлении нет функции «${entry}»`);
    }
    const аргумент = py.toPy(payload ?? {});
    let ответ;
    try {
      ответ = fn(аргумент);
    } finally {
      аргумент.destroy?.();
      fn.destroy?.();
    }
    return ответ?.toJs
      ? ответ.toJs({ dict_converter: Object.fromEntries })
      : ответ;
  } finally {
    область.destroy?.();
  }
}
