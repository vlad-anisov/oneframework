/**
 * Действие, **скомпилированное** в WebAssembly, -- третий способ запуска.
 *
 * Три способа, и они разные по существу, а не по оформлению:
 *
 * * **питон** -- в приложение кладётся *дополнительный интерпретатор*
 *   (Pyodide), и он исполняет исходник;
 * * **JavaScript** -- исполняет *встроенный* движок, тот самый, на котором
 *   работает весь webview; закладывать нечего;
 * * **компилируемые** (Kotlin, Rust, C++, Go, Swift) -- на сборке из них
 *   получается `.wasm`, и здесь он **инстанцируется**. Ни интерпретатора, ни
 *   исходника: в приложение едет машинный код для стековой машины.
 *
 * Отсюда и разница в цене. Питон стоит 13 МБ и секунды подъёма. JavaScript --
 * ноль. Модуль -- столько, сколько весит он сам: у Kotlin со стандартной
 * библиотекой внутри это 624 КБ, у Rust с тремя библиотеками -- 62 КБ.
 *
 * Kotlin/Wasm требует WasmGC, то есть достаточно свежего движка. Не заведётся
 * -- скажет об этом вслух: молчаливое «просто не работает» здесь хуже всего.
 */

/** Уже поднятые модули: инстанцировать один и тот же дважды незачем. */
const поднятые = new Map();

//: Корень приложения; ставит `worker.js`, как и у питона.
let БАЗА = "/";

export function setWasmBase(base) {
  БАЗА = base || "/";
}

/**
 * Поднять скомпилированный модуль и вернуть то, что он экспортирует.
 *
 * `module` -- имя, под которым сборка положила его в приложение. Рядом с
 * `.wasm` лежит склейка `.mjs`, которую делает тот же компилятор: она знает,
 * какие импорты подать модулю, и подменять её своей значило бы поддерживать
 * чужой договор руками.
 */
export async function loadWasmModule(имя) {
  let готовый = поднятые.get(имя);
  if (!готовый) {
    готовый = (async () => {
      try {
        // Обвязку кладёт сборка рядом с модулем -- это файл самого TeaVM,
        // а не наш. Подавать модулю тридцать импортов руками значило бы
        // поддерживать чужой договор вручную.
        const обвязка = await import(/* @vite-ignore */ `${БАЗА}wasm/${имя}/runtime.mjs`);
        const поднято = await обвязка.load(`${БАЗА}wasm/${имя}/${имя}.wasm`);
        return поднято.exports.Entry;
      } catch (отказ) {
        throw new Error(
          `модуль «${имя}» не поднялся: ${отказ && отказ.message}.\n`
          + "Модулю нужен WasmGC -- на старом движке он не заведётся.");
      }
    })();
    поднятые.set(имя, готовый);
  }
  return готовый;
}

/**
 * Позвать точку входа скомпилированного модуля.
 *
 * Кадр едет **строкой**: у стековой машины нет ни словарей, ни списков, и
 * договор (`protocol/logic.json`) уже говорит, что через границу ходит
 * UTF-8 JSON. Так одинаково для Kotlin, Rust и всех прочих.
 */
export async function runWasmAction(имя_модуля, entry, payload) {
  const экспорт = await loadWasmModule(имя_модуля);
  const fn = экспорт[entry];
  if (typeof fn !== "function") {
    throw new Error(`в модуле «${имя_модуля}» нет функции «${entry}»: `
      + `есть ${Object.keys(экспорт).join(", ") || "ничего"}`);
  }
  const ответ = fn(JSON.stringify(payload ?? {}));
  return typeof ответ === "string" ? JSON.parse(ответ) : ответ;
}
