/**
 * Действие на JavaScript -- самая дешёвая из трёх дорог.
 *
 * Рантайма закладывать не надо: он уже стоит, это сам webview. Поэтому
 * объявление везёт **текст**, как у питона, а исполняет его не интерпретатор
 * в песочнице, а движок, который и так работает.
 *
 * Kotlin сюда **не** приезжает, хотя раньше здесь было написано обратное:
 * `.kt` объявлен как `wasm` (`oneframework/device.py`), компилируется TeaVM в
 * WebAssembly и исполняется `wasm_action.js`. Дорога через `kotlinc-js`
 * разбиралась и отменена, её сборщик удалён 21.08.2026.
 *
 * `language` в объявлении говорит, чем действие написано, а не чем
 * исполняется.
 *
 * Что важно про песочницу. Прямого доступа к DOM здесь нет и быть не должно:
 * действие живёт в воркере, где `document` отсутствует, а всё, что оно может
 * попросить у приложения, приходит кадром и уходит ответом. Это не защита от
 * злого умысла -- код всё равно свой, -- а граница, из-за которой действие
 * нельзя написать так, чтобы оно работало в браузере и ломалось на телефоне.
 */

/** Кэш разобранных функций: разбирать один и тот же текст на каждый вызов незачем. */
const разобранные = new Map();

/**
 * Выполнить объявленный кусок JavaScript.
 *
 * `source` -- текст модуля, приехавший определением. `entry` -- имя функции,
 * которую он объявил. Кадр и ответ -- обычные значения, как у питона.
 *
 * Ошибка поднимается как есть: подменять её своей значило бы спрятать строку
 * и место, а это единственное, чем ошибка полезна.
 */
export async function runJsAction(source, entry, payload) {
  let фабрика = разобранные.get(source);
  if (!фабрика) {
    // `new Function`, а не `import()`: модуль из строки потребовал бы
    // blob-адреса, а он в webview под `capacitor://` ведёт себя иначе, чем в
    // браузере. Разница в поведении между сборками -- ровно то, чего здесь
    // допускать нельзя.
    //
    // `module` и `exports` даются потому, что сборщики кладут вывод по-разному:
    // UMD сам решает, куда себя положить, и без них кладёт в глобальное имя.
    // Своими руками написанное действие пишет туда же -- `exports.имя = ...`,
    // -- и обе дороги сходятся в одном месте.
    фабрика = new Function("module", "exports", `"use strict";\n${source}`);
    разобранные.set(source, фабрика);
  }
  const модуль = { exports: {} };
  фабрика.call(модуль, модуль, модуль.exports);
  const fn = модуль.exports[entry];
  if (typeof fn !== "function") {
    throw new Error(`в объявлении нет функции «${entry}»: `
      + `есть ${Object.keys(модуль.exports).join(", ") || "ничего"}`);
  }
  return await fn(payload ?? {});
}
