/**
 * SHA-256 -- проверенной библиотекой, а не своей рукой.
 *
 * Почему не `crypto.subtle`: он **асинхронный**, а хешируем мы changeset внутри
 * транзакции и отпечаток определения при выкладке. В обоих местах `await`
 * означал бы, что между снятием changeset и его записью в очередь успевает
 * произойти что-то ещё. Ради одного вызова разворачивать всю запись в промисы
 * нельзя -- нужен синхронный хеш.
 *
 * Синхронный -- не повод писать свой: криптографический примитив, написанный
 * руками, остаётся тем разрядом кода, где ошибка не видна ни глазом, ни
 * обычной проверкой. `@noble/hashes` даёт ровно то же синхронно: ноль
 * зависимостей, MIT, проверенная реализация.
 *
 * Отпечаток обязан совпадать с питоновским байт в байт: по нему changeset
 * узнают на другой стороне и по нему же решают, слать ли определение. Сторож --
 * `tests/test_js_sha256_parity.py`, и он сверяет с `hashlib`, а не сам с собой.
 */
import { sha256 } from "@noble/hashes/sha2.js";

const BYTE_HEX = Array.from({ length: 256 }, (_, i) => i.toString(16).padStart(2, "0"));

/** Шестнадцатеричный отпечаток **байтов**. Строку сюда передавать нельзя. */
export function sha256Hex(bytes) {
  const дайджест = sha256(bytes);
  let out = "";
  for (let i = 0; i < дайджест.length; i += 1) out += BYTE_HEX[дайджест[i]];
  return out;
}
