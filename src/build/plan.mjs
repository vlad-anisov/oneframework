/**
 * План выкладки: что положить в базу приложения, без единого обращения к ней.
 *
 * Порт `oneframework/cli/plan.py`. Порт, а не вторая реализация: питоновский
 * остаётся ровно до тех пор, пока `test_js_plan.py` сверяет их вывод строка в
 * строку, и уходит вместе с этой сверкой. Две живые копии одного правила
 * расходятся молча -- этим каркас уже болел, и лечится это не бдительностью, а
 * тем, что копия одна.
 *
 * Зачем переносить. Ядро -- договор, сборка и рантайм -- должно ставиться без
 * привязки к языку: человек, пишущий на Kotlin, не обязан ставить питон, чтобы
 * собрать своё приложение. Пока сборщик на питоне, «поставить ядро» и
 * «поставить привязку Python» -- одна и та же установка.
 *
 * Дорога сюда одна: **пакет объявления**. Питон, Kotlin и JavaScript входят
 * одной дверью, и сборка про их DSL ничего не знает.
 */

import { createPrivateKey, createPublicKey } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";

import { isDeclarative } from "../rel/action.js";
import { parseExpr } from "./exprtext.mjs";

/** Переменная, из которой сборка узнаёт ключ издателя. */
export const ENV_PRIVATE_KEY = "PYAPP_SIGNING_KEY";

export class BuildError extends Error {}

/**
 * Пакет объявления -> всё, что нужно положить в базу приложения.
 *
 * Возвращает то, что читает `build-db.mjs`: схему, определения и строки
 * посева. Порядок определений сохраняется -- по нему считается ревизия.
 */
export function buildPlan(пакет) {
  if (!пакет || !Array.isArray(пакет.models)) {
    throw new BuildError(
      "buildPlan принимает пакет объявления. Дорога одна намеренно -- иначе у " +
      "каждого языка был бы свой путь мимо договора, и ядро без его привязки " +
      "собрало бы другое приложение.",
    );
  }

  const определения = [
    ["types", "_", пакет.types],
    ...пакет.models.map((м) => ["model", м.name, развернутьТекст(м)]),
    ...пакет.views.map((в) => ["view", в.name, развернутьТекст(в)]),
  ];

  // Логика -- теми же определениями, что модели и виды: у объявленного
  // действия нет ни байтов, ни точки входа, и едет оно той же дорогой.
  for (const запись of пакет.logic || []) {
    if (запись.module) {
      throw new BuildError(
        `Логика модулем (${запись.module}) больше не поддерживается: хранение ` +
        "байтов удалено вместе с рантаймом WASM 16.08.2026.",
      );
    }
    for (const действие of запись.actions || []) {
      if (!isDeclarative({ ...действие })) {
        throw new BuildError(
          `Объявление '${действие.name}' без модуля обязано нести «rule» и «write».`,
        );
      }
      определения.push(["action", действие.name, развернутьТекст({ ...действие })]);
    }
  }

  return {
    schema: схемаПакета(пакет),
    defs: определения,
    seeds: (пакет.seeds || []).map((п) => ({ ...п })),
    // Ключ издателя -- в мете: по нему устройство проверяет подпись.
    publisher: публичныйКлюч(),
  };
}

/**
 * Схема для `makeModels` -- прямо из документов пакета.
 *
 * Третьей записи правила создания таблиц нет: таблицы заводит `db.ensureSchema`,
 * одна на всех. Пакет отдаёт только описание.
 */
function схемаПакета(пакет) {
  return { version: 1, types: пакет.types, models: [...пакет.models] };
}

/**
 * Открытый ключ издателя -- 64 шестнадцатеричных знака, если ключ назван.
 *
 * Голыми 32 байтами, а не PEM: на устройстве он попадает в
 * `crypto.subtle.importKey("raw", ...)`, которому нужны именно они. В DER от
 * SPKI ключ Ed25519 лежит последними 32 байтами -- заголовок у него постоянной
 * длины, поэтому хвост и есть ключ.
 *
 * Ключ **назван и негоден** -- отказ: молча собрать неподписанное вместо
 * подписанного значит выдать одно за другое. Ключ не назван вовсе -- не отказ,
 * а ответ: сборка без подписи законна и обязана собираться.
 */
function публичныйКлюч() {
  const назван = process.env[ENV_PRIVATE_KEY];
  if (!назван) return null;
  const файл = назван.startsWith("~")
    ? path.join(os.homedir(), назван.slice(1))
    : назван;
  if (!existsSync(файл)) {
    throw new BuildError(
      `${ENV_PRIVATE_KEY} указывает на ${файл}, а такого файла нет. ` +
      "Создать пару -- `oneframework keygen <файл>`.",
    );
  }
  let der;
  try {
    der = createPublicKey(createPrivateKey(readFileSync(файл))).export({
      type: "spki", format: "der",
    });
  } catch (отказ) {
    throw new BuildError(
      `${ENV_PRIVATE_KEY} указывает на ${файл}, но это не ключ Ed25519: ` +
      `${отказ.message}`,
    );
  }
  return Buffer.from(der.subarray(der.length - 32)).toString("hex");
}


/**
 * Развернуть выражения, записанные строкой, в обычные деревья.
 *
 * Узел `{"text": "..."}` живёт **только на проводе**: привязке дешевле
 * передать строку, чем встраивать выражения в свой язык. В выложенный
 * документ он не попадает -- дальше едет то же дерево, что и раньше, и рантайм
 * про строки не знает.
 *
 * Признак -- ровно один ключ `text` и ничего больше. Сегодня ключа `text` не
 * несёт ни один узел договора, так что хватило бы и вхождения; строго -- ради
 * завтрашнего: заведут узел вида с подписью в ключе `text`, и вхождение
 * развернуло бы подпись в выражение. Заметить это можно было бы только по
 * пустому экрану.
 *
 * Ключ один, а значение не строка -- отказ разборщика, а не пропуск: это
 * записанное с ошибкой выражение, и молча оставленное, оно доедет до
 * устройства, где его никто не прочтёт.
 */
export function развернутьТекст(значение) {
  if (Array.isArray(значение)) return значение.map(развернутьТекст);
  if (!значение || typeof значение !== "object") return значение;
  const ключи = Object.keys(значение);
  // Не строку отвергает сам разборщик, теми же словами: своя проверка здесь
  // только повторяла бы его, а повторённое правило нечем проверить -- снятое,
  // оно оставляет сюиту зелёной.
  if (ключи.length === 1 && ключи[0] === "text") return parseExpr(значение.text);
  const из = {};
  for (const [к, v] of Object.entries(значение)) из[к] = развернутьТекст(v);
  return из;
}
