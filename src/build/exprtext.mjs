/**
 * Выражение строкой -> дерево узлов договора.
 *
 * Зачем. Сегодня выражение нельзя написать -- его можно только **построить**,
 * запустив язык: питон делает это перегрузкой операторов (33 класса, 80
 * методов вида `__eq__`), Kotlin -- инфиксными функциями. За одну и ту же
 * выразительность питон платит 257 строк против 56, и так будет в каждой новой
 * привязке. Хуже другое: `Expr.kt` покрывает семь родов узлов из четырнадцати,
 * и на Kotlin нельзя объявить ни арифметику, ни свёртку по набору.
 *
 * Разборщик один и живёт здесь. Привязке достаточно передать строку -- дерево
 * соберёт ядро. Четвёртый язык обходится в одну функцию вместо тридцати трёх
 * классов.
 *
 * Почему в сборке, а не в рантайме: текст разворачивается **на сборке**, и в
 * базу едет то же дерево, что и раньше. Рантайм про строки не знает и знать не
 * должен -- иначе разбор пришлось бы возить на устройство.
 *
 * Перечень узлов здесь не пересказан: он один на все языки и лежит в
 * `protocol/expression.json`.
 */

export class ExprTextError extends Error {}

/** Приставки ссылок. Что за ними -- решает договор, не разборщик. */
const ССЫЛКИ = { record: "r", view: "v", item: "i" };

/** Действия арифметики от одного и двух доводов -- имена из договора. */
const ФУНКЦИИ = {
  abs: 1, neg: 1, length: 1, lower: 1, upper: 1, trim: 1, ltrim: 1, rtrim: 1,
  text: 1, integer: 1, real: 1,
  round: [1, 2], startswith: 2, endswith: 2, replace: 3, if: 3,
};

const СРАВНЕНИЯ = ["!=", "<=", ">=", "=", "<", ">"];

// --------------------------------------------------------------------------
// разбор на слова
// --------------------------------------------------------------------------
function слова(текст) {
  const из = [];
  let i = 0;
  const n = текст.length;
  while (i < n) {
    const c = текст[i];
    if (c === " " || c === "\t" || c === "\n") { i += 1; continue; }
    if (c === '"' || c === "'") {
      let j = i + 1, значение = "";
      while (j < n && текст[j] !== c) {
        if (текст[j] === "\\" && j + 1 < n) { значение += текст[j + 1]; j += 2; continue; }
        значение += текст[j]; j += 1;
      }
      if (j >= n) throw new ExprTextError(`строка не закрыта: ${текст.slice(i, i + 20)}`);
      из.push({ род: "строка", значение }); i = j + 1; continue;
    }
    if (/[0-9]/.test(c) || (c === "." && /[0-9]/.test(текст[i + 1] || ""))) {
      let j = i;
      while (j < n && /[0-9.]/.test(текст[j])) j += 1;
      const кусок = текст.slice(i, j);
      if ((кусок.match(/\./g) || []).length > 1) {
        throw new ExprTextError(`не число: ${кусок}`);
      }
      из.push({ род: "число", значение: Number(кусок) }); i = j; continue;
    }
    if (/[A-Za-z_Ѐ-ӿ]/.test(c)) {
      let j = i;
      while (j < n && /[A-Za-z0-9_Ѐ-ӿ]/.test(текст[j])) j += 1;
      из.push({ род: "слово", значение: текст.slice(i, j) }); i = j; continue;
    }
    const два = текст.slice(i, i + 2);
    if (["!=", "<=", ">=", "**", "//"].includes(два)) {
      из.push({ род: "знак", значение: два }); i += 2; continue;
    }
    if ("=<>+-*/%&|!().,".includes(c)) {
      из.push({ род: "знак", значение: c }); i += 1; continue;
    }
    throw new ExprTextError(`непонятный знак «${c}» в позиции ${i}`);
  }
  return из;
}

// --------------------------------------------------------------------------
// разбор в дерево
// --------------------------------------------------------------------------
class Разбор {
  constructor(текст) {
    this.текст = текст;
    this.слова = слова(текст);
    this.i = 0;
  }

  гляди() { return this.слова[this.i]; }

  это(род, значение) {
    const с = this.гляди();
    return !!с && с.род === род && (значение === undefined || с.значение === значение);
  }

  бери(род, значение) {
    if (!this.это(род, значение)) {
      const с = this.гляди();
      throw new ExprTextError(
        `ждали ${значение ? `«${значение}»` : род}, а тут ` +
        (с ? `«${с.значение}»` : "конец строки") + `: ${this.текст}`);
    }
    return this.слова[this.i++];
  }

  /** Всё выражение. Остаток -- отказ: молча брошенный хвост меняет смысл. */
  разбери() {
    const дерево = this.или();
    if (this.i < this.слова.length) {
      throw new ExprTextError(
        `лишнее после выражения: «${this.слова[this.i].значение}» в ${this.текст}`);
    }
    return дерево;
  }

  или() {
    const части = [this.и()];
    while (this.это("знак", "|")) { this.i += 1; части.push(this.и()); }
    return части.length === 1 ? части[0] : { op: "|", p: части };
  }

  и() {
    const части = [this.сравнение()];
    while (this.это("знак", "&")) { this.i += 1; части.push(this.сравнение()); }
    return части.length === 1 ? части[0] : { op: "&", p: части };
  }

  сравнение() {
    let левое = this.сложение();
    // `x is null` -- отдельный род узла: у SQL пусто не равно ничему, включая
    // само себя, и записать это сравнением нельзя.
    if (this.это("слово", "is")) {
      this.i += 1;
      const отрицание = this.это("слово", "not");
      if (отрицание) this.i += 1;
      this.бери("слово", "null");
      const пусто = { op: "null", e: левое };
      return отрицание ? { op: "!", e: пусто } : пусто;
    }
    const с = this.гляди();
    if (с && с.род === "знак" && СРАВНЕНИЯ.includes(с.значение)) {
      this.i += 1;
      левое = { op: с.значение, l: левое, r: this.сложение() };
    }
    return левое;
  }

  сложение() {
    let левое = this.умножение();
    while (this.это("знак", "+") || this.это("знак", "-")) {
      const op = this.слова[this.i++].значение;
      левое = { op, args: [левое, this.умножение()] };
    }
    return левое;
  }

  умножение() {
    let левое = this.степень();
    while (["*", "/", "//", "%"].some((з) => this.это("знак", з))) {
      const op = this.слова[this.i++].значение;
      левое = { op, args: [левое, this.степень()] };
    }
    return левое;
  }

  /** Степень правоассоциативна: `2 ** 3 ** 2` -- это `2 ** (3 ** 2)`. */
  степень() {
    const левое = this.одиночное();
    if (this.это("знак", "**")) {
      this.i += 1;
      return { op: "**", args: [левое, this.степень()] };
    }
    return левое;
  }

  одиночное() {
    if (this.это("знак", "!")) { this.i += 1; return { op: "!", e: this.одиночное() }; }
    if (this.это("знак", "-")) { this.i += 1; return { op: "neg", args: [this.одиночное()] }; }
    return this.простое();
  }

  простое() {
    if (this.это("знак", "(")) {
      this.i += 1;
      const внутри = this.или();
      this.бери("знак", ")");
      return внутри;
    }
    const с = this.гляди();
    if (!с) throw new ExprTextError(`выражение оборвалось: ${this.текст}`);
    if (с.род === "число" || с.род === "строка") { this.i += 1; return с.значение; }
    if (с.род !== "слово") {
      throw new ExprTextError(`здесь ждали значение, а тут «${с.значение}»: ${this.текст}`);
    }
    this.i += 1;
    const имя = с.значение;

    if (имя === "true") return true;
    if (имя === "false") return false;
    if (имя === "null") return null;
    if (имя === "unset") return { unset: true };

    if (имя in ССЫЛКИ) {
      this.бери("знак", ".");
      const поле = this.бери("слово").значение;
      return { [ССЫЛКИ[имя]]: поле };
    }

    if (this.это("знак", "(")) return this.вызов(имя);

    throw new ExprTextError(
      `неизвестное слово «${имя}»: ${this.текст}\n` +
      `    поле пишется «record.${имя}», состояние вида -- «view.${имя}»`);
  }

  вызов(имя) {
    if (!(имя in ФУНКЦИИ)) {
      throw new ExprTextError(
        `нет такого действия: «${имя}». Есть: ${Object.keys(ФУНКЦИИ).sort().join(", ")}`);
    }
    this.бери("знак", "(");
    const доводы = [];
    if (!this.это("знак", ")")) {
      доводы.push(this.или());
      while (this.это("знак", ",")) { this.i += 1; доводы.push(this.или()); }
    }
    this.бери("знак", ")");
    const сколько = ФУНКЦИИ[имя];
    const годится = Array.isArray(сколько)
      ? сколько.includes(доводы.length) : доводы.length === сколько;
    if (!годится) {
      throw new ExprTextError(
        `«${имя}» ждёт ${Array.isArray(сколько) ? сколько.join(" или ") : сколько} ` +
        `довод(а), дано ${доводы.length}: ${this.текст}`);
    }
    return { op: имя, args: доводы };
  }
}

/** Строка -> дерево узлов договора. Отказ вслух, с указанием места. */
export function parseExpr(текст) {
  if (typeof текст !== "string") {
    throw new ExprTextError(`выражение записывается строкой, дано ${typeof текст}`);
  }
  return new Разбор(текст).разбери();
}
