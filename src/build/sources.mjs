/**
 * Откуда сборка берёт приложение: расширение файла -> пакет объявления.
 *
 * Язык виден по файлу, а не по флагу. Это единственное место, где ядро знает
 * про существование языков, и знает оно немного: чем позвать привязку и как
 * забрать у неё пакет.
 *
 * Место ему здесь, а не у какой-то из привязок. Диспетчер, живущий у одной из
 * них, делает её обязательной для всех: пока он стоял у питона, человек с
 * приложением на Kotlin ставил питон, чтобы собрать свой же Kotlin.
 *
 * У привязки просят две вещи, и обе -- то, чего ядро не умеет:
 *
 * * **пакет объявления** -- единственный договор между языком и сборкой;
 * * **добавку** -- исходники виджетов и стилей, объявленных модулями. Едут
 *   исходником, а не ссылкой: файлы лежат в дереве приложения, а не на
 *   веб-сервере, и так они одинаково работают офлайн и внутри APK. Найти их
 *   умеет только та привязка, чьим языком приложение написано.
 *
 * Привязка может сделать и третье -- привезти на устройство свой рантайм
 * (питон возит Pyodide). Отдельной команды на это нет: привязка делает это
 * сама, когда её зовут с `--root`, потому что решение возить или не возить
 * принимается по объявлению, а объявление в этот момент у неё в руках.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";

/** Отказ, который человеку показывают как есть -- без стека и без «ошибка». */
export class SourceError extends Error {}

const ПУСТАЯ_ДОБАВКА = { scripts: [], styles: [] };

//: Что привязка объявила, но собрать не смогла: имя -> отказ. Пропуск --
//: решение привязки, а не беда сборки: приложение с недописанным видом обязано
//: собираться. Но `check` обязан назвать пропущенное поимённо.
const БЕЗ_ПРОПУСКОВ = {};

/**
 * Пакет объявления и добавка по файлу приложения.
 *
 * @param {string} appFile -- `.py`, `.mjs`, `.kt` или готовый `.json`
 * @param {{root?: string}} опции -- `root` передаётся привязке: с ним она
 *   везёт на устройство свой рантайм, без него только печатает пакет.
 * @returns {Promise<{bundle: object, extra: object, skipped: object}>}
 */
export async function bundleOf(appFile, { root = null } = {}) {
  const полный = path.resolve(appFile);
  if (!existsSync(полный)) throw new SourceError(`${appFile}: файла нет`);
  const как = ИСТОЧНИКИ[path.extname(полный)];
  if (!как) {
    throw new SourceError(
      `${appFile}: не знаю такого языка. Приложение -- это `
      + `${Object.keys(ИСТОЧНИКИ).join(", ")} либо готовый пакет объявления.`);
  }
  return как(полный, root);
}

/** Готовый пакет: читать и не звать никого. */
function изПакета(полный) {
  return { bundle: JSON.parse(readFileSync(полный, "utf8")),
           extra: ПУСТАЯ_ДОБАВКА, skipped: БЕЗ_ПРОПУСКОВ };
}

/**
 * JavaScript: файл приложения ввозится прямо, привязка -- рядом с ним.
 *
 * Ввозится, а не запускается подпроцессом, как питон: мы уже в node, и своё
 * приложение оно поднимет в этом же процессе. Привязка ищется от файла
 * приложения, а не от ядра: у приложения она в зависимостях, у ядра её нет.
 */
async function изJavaScript(полный) {
  const модуль = await import(pathToFileURL(полный).href);
  // `application` или `default` -- оба вывоза живые, и оба в примерах. Один
  // выбрать было бы правильнее, но выбор этот принадлежит привязке, а не
  // диспетчеру: сломается он здесь, а объяснять придётся там.
  const приложение = модуль.application ?? модуль.default;
  if (!приложение) {
    throw new SourceError(
      `${полный}: нет ни \`application\`, ни экспорта по умолчанию. Файл`
      + " приложения заканчивается\n    export const application = app({ ... });");
  }
  const { declare } = await привязкаJS(полный);
  return { bundle: declare(приложение), extra: ПУСТАЯ_ДОБАВКА, skipped: БЕЗ_ПРОПУСКОВ };
}

async function привязкаJS(отФайла) {
  // Сначала рядом с приложением -- так работает установленное; потом соседняя
  // папка в дереве разработки, где привязка ещё не издана.
  for (const кандидат of [
    path.join(path.dirname(отФайла), "node_modules", "oneframework-js", "index.mjs"),
    path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "..", "index.mjs"),
  ]) {
    if (existsSync(кандидат)) return import(pathToFileURL(кандидат).href);
  }
  throw new SourceError(
    "Приложение на JavaScript, а привязки нет: npm i oneframework-js");
}

/**
 * Kotlin: собрать под JVM и запустить -- пакет печатает сама программа.
 *
 * Компилятор Kotlin нужен, и он же и так нужен тому, кто пишет на Kotlin.
 */
async function изKotlin(полный) {
  const { declare } = await import("./kotlin.mjs");
  return { bundle: declare(полный), extra: ПУСТАЯ_ДОБАВКА, skipped: БЕЗ_ПРОПУСКОВ };
}

/**
 * Питон: запустить интерпретатор и забрать написанное им в каталог.
 *
 * Подпроцессом, а не как-то иначе: питон -- чужой рантайм, и внутрь node он не
 * ввозится. Через каталог, а не через stdout: файлов два (пакет и добавка), и
 * ловить их из одного потока значило бы завести свой формат там, где хватает
 * двух имён.
 */
async function изПитона(полный, root) {
  const каталог = mkdtempSync(path.join(tmpdir(), "oneframework-py-"));
  const доводы = ["-m", "oneframework", "declare", полный, "--out", каталог];
  if (root) доводы.push("--root", root);
  try {
    execFileSync(питон(), доводы, { stdio: ["ignore", "inherit", "inherit"] });
  } catch (отказ) {
    throw new SourceError(
      отказ.status !== undefined
        ? `${path.basename(полный)}: питон отказался напечатать пакет.`
        : `Приложение на питоне, а питона нет: ${отказ.message}`);
  }
  const пакет = path.join(каталог, "пакет.json");
  if (!existsSync(пакет)) {
    throw new SourceError(
      "Питон отработал, а пакета не написал. Так бывает, когда установлена "
      + "привязка старее ядра: pip install -U oneframework");
  }
  const прочесть = (имя, если_нет) => {
    const где = path.join(каталог, имя);
    return existsSync(где) ? JSON.parse(readFileSync(где, "utf8")) : если_нет;
  };
  return {
    bundle: JSON.parse(readFileSync(пакет, "utf8")),
    extra: прочесть("добавка.json", ПУСТАЯ_ДОБАВКА),
    skipped: прочесть("пропуски.json", БЕЗ_ПРОПУСКОВ),
  };
}

/** Чем звать питон. `PYTHON` перебивает -- там, где их несколько. */
function питон() {
  return process.env.PYTHON || process.env.PYAPP_PYTHON || "python3";
}

//: Расширение -> чем читается. Порядок здесь ни на что не влияет, но список
//: этот -- ответ на вопрос «на чём можно писать приложение», и другого места,
//: где он записан, нет.
const ИСТОЧНИКИ = {
  ".json": изПакета,
  ".mjs": изJavaScript,
  ".js": изJavaScript,
  ".kt": изKotlin,
  ".py": изПитона,
};

/** Языки, которые ядро умеет прочитать. Для сообщений и для проверок. */
export const ЯЗЫКИ = Object.keys(ИСТОЧНИКИ);
