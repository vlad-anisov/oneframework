/**
 * Адрес страницы -- проекция кадра, а не его номер.
 *
 * Стек принадлежит рантайму, маршрутизатор ведомый. Раз так, адрес обязан
 * говорить о кадре всё, что нужно странице, чтобы найти себя саму: раздел, вид,
 * запись. Номер глубины, стоявший здесь раньше (`/screen/:index/`), не говорил
 * ни одного из трёх -- отсюда и «страница ищет свой кадр по счёту», и общий на
 * все записи ключ прокрутки.
 *
 * `?f=` -- сам кадр, и он здесь не ради полноты. `allowDuplicateUrls` у вида
 * выключен (`components/view/view.js:55`), а переход на адрес, равный текущему,
 * Framework7 молча отменяет (`navigate.js:417`, `back.js:319`). Без кадра в
 * адресе «открыть ту же запись поверх себя» стало бы отменяемым переходом, и
 * сведение стека ждало бы события, которого уже не будет. Заодно ячейка
 * `scrollHistory` (`router-class.js:683`) заводится по адресу -- то есть
 * становится «прокрутка этого кадра», а не «прокрутка этой глубины».
 *
 * Запросом, а не сегментом, потому что путь тогда остаётся ровно той формой,
 * которая нужна для адресной строки: `/s/<раздел>/<вид>/<запись>/`.
 */

/** Ключ раздела и имя вида -- из объявления, туда попадает что угодно. */
const seg = (value) => encodeURIComponent(String(value));

/**
 * Корень раздела.
 *
 * Отдельным маршрутом, а не первым случаем общего -- почему, разобрано у
 * `ROUTES` в `web/src/react/shell.jsx`: там же и лежит то самое `master`.
 */
export const rootUrl = (screenKey) => `/s/${seg(screenKey)}/`;

/** Пустая половина разделённого экрана -- такая же страница, как всякая. */
export const EMPTY_URL = "/empty/";

/** Адрес кадра. Корень стека -- корень раздела, всё остальное -- запись. */
export function frameUrl(screenKey, frame, index) {
  if (index === 0) return rootUrl(screenKey);
  // Черновик -- запись, у которой ещё нет ключа; вид-раздел в глубине стека --
  // кадр вообще без записи. Оба -- законные адреса, и различить их надо.
  const record = frame.draft ? "new" : frame.record_id;
  return `/s/${seg(screenKey)}/${seg(frame.view || "-")}/${seg(record ?? "-")}/`
    + `?f=${seg(frame.id)}`;
}

/**
 * Кадр, чью страницу называет адрес, -- обратное к `frameUrl`.
 *
 * Здесь, а не у спрашивающего: `?f=` придумано в этом файле, и знать его форму
 * должен один файл. У корня раздела и у пустой половины кадра в адресе нет --
 * обе стоят на своих местах независимо от того, что сейчас в стеке, и ответ
 * `null` для них правдив, а не «не нашли».
 */
export const frameOf = (url) =>
  new URLSearchParams(String(url).split("?")[1] || "").get("f");

/**
 * Стек -> адреса страниц вида.
 *
 * В разделённом окне корень тянет за собой пустую половину: она такая же
 * страница маршрутизатора, как запись, и стоит на том же месте. Значит и в
 * истории она стоит там же -- иначе снять её было бы нечем: с карточки на
 * мастера Framework7 в разделённом окне назад не идёт вовсе
 * (`back.js:490-505,548-550`, `skipMaster`), и «назад» просто не состоялось бы.
 */
export function stackUrls(screenKey, frames, split) {
  const urls = frames.map((frame, index) => frameUrl(screenKey, frame, index));
  if (split && urls.length === 1) urls.push(EMPTY_URL);
  return urls;
}

/** Сколько адресов в начале двух путей совпадает. */
export function commonPrefix(a, b) {
  let n = 0;
  while (n < a.length && n < b.length && a[n] === b[n]) n += 1;
  return n;
}
