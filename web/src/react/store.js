/**
 * Всё, что знает оболочка, в одном месте -- и подписка на это из React.
 *
 * Кадр приходит не из React: его присылает рантайм в ответ на событие, а обмен
 * -- когда захочет. Такому источнику нужен `useSyncExternalStore`, а не
 * состояние компонента: подписчиков много (страница, значок обмена, панель), а
 * пишущий -- снаружи дерева.
 *
 * Три вещи лежат здесь по трём разным причинам:
 *
 *   snapshot -- кадр от рантайма, единственный источник правды об экранах;
 *   sync     -- состояние обмена: живёт дольше кадра и меняется чаще него;
 *   tabs     -- какая страница открыта в каждом Tabs. Это состояние оболочки,
 *               а не приложения: полоса вкладок -- один орган управления, и
 *               питон нарочно не знает, где её оставили.
 */
import { useSyncExternalStore } from "react";

export class Store {
  constructor() {
    this.state = { snapshot: null, sync: null, tabs: {}, title: "" };
    //: Виды Framework7 по разделам. Не состояние: их создаёт и убирает
    //: Framework7, перерисовке они не подлежат, а нужны и оболочке (свести
    //: стек), и хозяину страницы (кнопка «назад» телефона).
    this.frames = new Map();
    //: Деревья только что снятых кадров: `frame.id -> {tree, index}`. Кадра в
    //: снимке уже нет, а его страница ещё на экране -- маршрутизатор доигрывает
    //: возврат. Без этой памяти он анимировал бы пустоту: страница осталась бы
    //: в документе, а рисовать ей было бы нечего. Ячейка живёт ровно столько,
    //: сколько стоит страница (`releaseOutgoing`). Не состояние по той же
    //: причине, что и `frames`: пишет её оболочка, а не отрисовка.
    this.outgoing = new Map();
    this._subs = new Set();
    this.subscribe = this.subscribe.bind(this);
    this.get = this.get.bind(this);
  }

  subscribe(fn) {
    this._subs.add(fn);
    return () => this._subs.delete(fn);
  }

  get() {
    return this.state;
  }

  /**
   * Новое состояние -- новый объект.
   *
   * `useSyncExternalStore` сравнивает то, что вернул `get`, по ссылке: если
   * менять поля на месте, React не увидит ни одного изменения.
   */
  set(patch) {
    if ("snapshot" in patch) this._keepOutgoing(this.state.snapshot, patch.snapshot);
    this.state = { ...this.state, ...patch };
    for (const fn of [...this._subs]) fn();
  }

  /**
   * Запомнить кадры, которых в новом снимке уже нет.
   *
   * Здесь, при подмене снимка, а не эффектом после отрисовки: React
   * перерисовывается тем же тактом, и эффект опоздал бы ровно на ту отрисовку,
   * ради которой всё и делается -- на первую после снятия кадра. Место в стеке
   * хранится вместе с деревом: страница показывает стрелку «назад» и свой
   * номер по нему, и на возврате они должны остаться прежними.
   */
  _keepOutgoing(prev, next) {
    if (!prev || !next) return;
    for (const [key, frames] of Object.entries(prev.stacks || {})) {
      const live = new Set((next.stacks?.[key] || []).map((f) => f.id));
      // Помнится всё снятое без разбора -- в том числе то, у чего страницы нет
      // вовсе (карточка). Отбирать здесь значило бы завести второе правило о
      // том же: кому ячейка нужна, решает `releaseOutgoing`, и кадр без
      // страницы отпускается им на ближайшем же сведении.
      frames.forEach((tree, index) => {
        if (!live.has(tree.id)) this.outgoing.set(tree.id, { tree, index });
      });
    }
  }

  /**
   * Отпустить кадры, чьих страниц на экране больше нет.
   *
   * Спрашивается положение дел, а не событие, и это единственное правило на все
   * источники «назад». Нажатие и кнопку браузера оболочка проводит сама, и по
   * ним ячейку можно было бы отпускать событием `pageAfterOut`. По жесту --
   * нельзя: `swipe-back.js:238-246` убирает страницу *раньше*, чем шлёт
   * `routeChanged`, которым мы о жесте и узнаём, -- то есть раньше, чем рантайм
   * снимет кадр и ячейка вообще заведётся. Отпускать её было бы уже некому, и
   * дерево оставалось бы в памяти навсегда, по одному на каждый жест.
   */
  releaseOutgoing(live) {
    for (const id of this.outgoing.keys()) {
      if (!live.has(id)) this.outgoing.delete(id);
    }
  }

  /** Какая страница открыта в этом Tabs. */
  tab(id) {
    return this.state.tabs[id];
  }

  setTab(id, tab) {
    if (this.state.tabs[id] === tab) return false;
    this.set({ tabs: { ...this.state.tabs, [id]: tab } });
    return true;
  }
}

export const useStore = (store) => useSyncExternalStore(store.subscribe, store.get);
