/**
 * Одна граница на все подачи: ниже неё телефон, выше -- рабочий стол.
 *
 * Отдельным файлом, а не в оболочке, потому что спрашивают её двое: оболочка
 * (панель разделов, разделённый экран) и страница (крошки). Страница, взявшая
 * границу у оболочки, замкнула бы круг -- оболочка страницу и рисует.
 *
 * Готовых классов «показать только в широком окне» у Framework7 нет:
 * `display-none` есть, отзывчивых `medium-display-*` -- нет (проверено по
 * `framework7-bundle.css`). Значит спрашивать ширину всё равно кому-то придётся,
 * и пусть это будет одно место с одним числом, а не медиазапрос в чужом CSS
 * рядом с числом-двойником.
 */
import { useSyncExternalStore } from "react";

/** Та же граница, что у панели разделов и у разделённого экрана. */
export const WIDE_BREAKPOINT = 768;

//: Один запрос на всё приложение: `matchMedia` заводит наблюдателя, а
//: спрашивающих у нас столько, сколько страниц на экране.
let media = null;
const query = () => (media ||= window.matchMedia(`(min-width: ${WIDE_BREAKPOINT}px)`));

const subscribe = (onChange) => {
  const mql = query();
  mql.addEventListener("change", onChange);
  return () => mql.removeEventListener("change", onChange);
};

/**
 * Широко ли окно.
 *
 * `useSyncExternalStore`, а не пара «состояние плюс слушатель»: правда живёт
 * снаружи React, и этот приём для неё и заведён -- он же гарантирует, что все
 * спрашивающие увидят один ответ в одном такте, а не разъедутся на кадр.
 */
export const useWide = () => useSyncExternalStore(subscribe, () => query().matches);
