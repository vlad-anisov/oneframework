/**
 * Текст, который надо показать как есть.
 *
 * Ровно два случая, и оба -- сообщения об ошибке: трассировка при неудачном
 * запуске и надпись в красном блоке вместо сломанного виджета. Всё остальное,
 * что видит пользователь, приходит строкой из документа вида и попадает в
 * разметку через React, который экранирует сам.
 */

/** Подпись из DSL, безопасная в разметке. */
export const esc = (value) =>
  String(value ?? "").replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`);

/**
 * `<pre>` держит переводы строк, но отказывается переносить, а утилиты ни для
 * того, ни для другого у Framework7 нет -- поэтому переводы становятся `<br>`,
 * а отступы `&nbsp;`.
 */
export const preformatted = (text) =>
  esc(text)
    .split("\n")
    .map((line) =>
      line
        .replace(/^ +/, (run) => "&nbsp;".repeat(run.length))
        // Путь к файлу для переносчика строк -- одно длинное слово; `<wbr>`
        // говорит, где HTML разрешено разорвать его, и коробка держит путь
        // вместо того, чтобы им переполниться.
        .replace(/([/._-])/g, "$1<wbr />"),
    )
    .join("<br />");
