/**
 * Адресная строка -- проекция стека, и обратная дорога из неё.
 *
 * Форма адреса: `#!/<раздел>/(<вид>/<запись>/)*`. Первый сегмент -- раздел,
 * дальше по паре «вид -- запись» на кадр:
 *
 *     #!/Tasks/                              -- раздел Tasks, корень
 *     #!/Tasks/TaskCard/0192f3.../           -- в нём открыта запись
 *     #!/Tasks/TaskCard/0192f3.../Sub/019a.../  -- и из неё ещё одна
 *
 * Весь стек, а не одна его вершина. Иначе по ссылке восстанавливается место,
 * но не путь возврата: человек пришёл бы на запись, нажал «назад» и оказался
 * там, где никогда не был. Так же поступает Odoo -- `stateToUrl` раскладывает
 * в сегменты весь `actionStack`, а не текущее действие, -- и по той же причине.
 *
 * Почему адрес пишем сами, а не отдаём `browserHistory` маршрутизатору
 * Framework7. Состояние истории у него одно на приложение, а ключ в нём --
 * `view.id` (`shared/history.js:44-84`), тогда как адресная строка одна и
 * побеждает в ней последний навигировавший вид. На холодной загрузке -- а
 * глубокая ссылка это всегда холодная загрузка -- сохранённого состояния нет
 * вовсе, и **каждый** вид разбирает **один и тот же** адрес; вторичные уходят
 * в not-found. Раскладка у нас -- по виду на раздел, значит `browserHistory`
 * пришлось бы включать ровно одному виду, а раздел -- часть адреса, то есть
 * этот один вид менялся бы вместе с разделом. Свой `pushState` -- сорок строк,
 * и он пишет один адрес на всё приложение сознательно.
 *
 * Один адрес на приложение -- это и есть то самое ограничение, только принятое
 * сознательно: в строке стоит стек **активного** раздела, остальные остаются
 * там, где их оставили, и по ссылке встают на свои корни. Иначе и быть не
 * может -- строка одна, а стеков столько, сколько разделов; хранить их все в
 * ней значило бы писать в адрес то, чего человек не видит.
 *
 * Кто кого двигает. Стек принадлежит рантайму, адрес -- его снимок: всякая
 * смена стека переписывает адрес, и только `popstate` идёт в обратную сторону,
 * событием `goto`. Событие это идемпотентно (рантайм оставляет совпавшее
 * начало стека и достраивает остальное), поэтому круг между «мы написали
 * адрес» и «адрес переписал стек» замыкается на первом же шаге и не звенит.
 *
 * В нативной сборке адресной строки нет вовсе -- ни писать, ни читать нечего;
 * там дверь другая, и она внизу файла.
 */

/** `#!` -- тот же разделитель, что по умолчанию у Framework7. */
const PREFIX = "#!";

/** В ключе раздела, имени вида и ключе записи бывает что угодно. */
const seg = (value) => encodeURIComponent(String(value));

/** Адрес из разобранного вида -- он же канонический вид адреса. */
function format({ screen, path }) {
  const parts = [seg(screen)];
  for (const step of path) parts.push(seg(step.view), seg(step.record_id ?? "-"));
  return `${PREFIX}/${parts.join("/")}/`;
}

/**
 * Стек кадров -> `{screen, path}`.
 *
 * Корневой кадр пары не даёт: он и есть раздел. Дальше берутся страницы, и
 * ровно до первой, которая не страница:
 *
 *   * карточка (`target: "sheet"`) поднята над стеком, а не встала в него, --
 *     это состояние поверх места, а не место;
 *   * черновик записи ещё не существует, ссылаться не на что: адрес привёл бы
 *     на пустую форму чужого человека.
 *
 * И то, и другое отрезает хвост, а не пропускается: за ними в стеке может
 * стоять что угодно, и склеенный через пропуск путь описывал бы стек, которого
 * не было.
 */
export function project(screenKey, stack) {
  const path = [];
  for (const tree of stack.slice(1)) {
    if (tree.draft || tree.target !== "page") break;
    path.push({ view: tree.view, record_id: tree.record_id ?? null });
  }
  return { screen: screenKey, path };
}

/** Адрес активного раздела -- то, что должно стоять в строке. */
export const addressUrl = (screenKey, stack) => format(project(screenKey, stack));

/**
 * Адрес -> `{screen, path}`, или `null`, если это не наш адрес.
 *
 * Берётся всё после `#`, потому что то же самое разбирается и в нативе, где
 * приходит целая ссылка со схемой. Нет `#` -- нет адреса: `capacitor://localhost`
 * без него разобрался бы в раздел `capacitor:`.
 *
 * Адрес -- ввод снаружи, и он бывает каким угодно: набран руками, сохранён в
 * закладке до переименования вида, обрезан почтовым клиентом. Поэтому здесь ни
 * одного исключения наружу -- непонятное равносильно отсутствующему.
 */
export function parseAddress(text) {
  const raw = String(text ?? "");
  const at = raw.indexOf("#");
  if (at === -1) return null;
  try {
    const body = raw.slice(at + 1).replace(/^!/, "");
    const parts = body.split("/").filter(Boolean).map(decodeURIComponent);
    if (!parts.length) return null;
    const [screen, ...rest] = parts;
    const path = [];
    for (let i = 0; i < rest.length; i += 2) {
      // Пара без записи -- законный кадр: вид-раздел в глубине стека. В адресе
      // он стоит прочерком, чтобы пары не съехали.
      const record = rest[i + 1];
      path.push({ view: rest[i], record_id: !record || record === "-" ? null : record });
    }
    return { screen, path };
  } catch {
    return null;
  }
}

/**
 * Связать адресную строку со стеком. Возвращает отвязку.
 *
 * `native` -- сборка Capacitor: там вся дверь -- `bindLaunchUrl` внизу файла,
 * почему -- сказано у неё.
 */
export function bindAddress({ store, dispatch, native = false }) {
  const known = (key) =>
    (store.state.snapshot?.screens || []).some((s) => s.key === key);
  //: Раздел, которого в приложении нет, -- это чужая или устаревшая ссылка, и
  //: спрашивать о ней рантайм не за чем: он ответил бы исключением, а человек
  //: увидел бы красную плашку из-за опечатки в адресе. Пути это не касается:
  //: за него отвечает рантайм, он молча останавливается на первом шаге,
  //: которого не может исполнить, а строку потом поправит запись ниже.
  const go = (target) => {
    if (!target || !known(target.screen)) return null;
    // Ответ отдаётся наружу, а не проглатывается: по холодной ссылке подписка
    // ждёт именно его -- см. ниже.
    return dispatch({ type: "goto", screen: target.screen, path: target.path });
  };

  if (native) return bindLaunchUrl(go);

  const address = () => {
    const snap = store.state.snapshot;
    return snap ? addressUrl(snap.active, snap.stacks?.[snap.active] || []) : null;
  };

  //: Адрес, написанный нами последним. `null` -- ещё ни разу: первая запись
  //: делается заменой, а не добавлением, потому что первое место -- то самое,
  //: на которое человек и пришёл, и отдельной записи в истории оно не стоит.
  let written = null;
  //: Сколько своих записей лежит в истории **под** текущей. Живёт не только
  //: переменной, но и состоянием самой записи (`{of}`): `popstate` иначе не
  //: отличить от своего же возврата, а прыжок через несколько записей -- от шага.
  let depth = 0;
  //: Свои записи истории адресами, снизу вверх: `trail[of]` -- то, что стоит в
  //: записи глубины `of`. Нужен он ради возврата сразу через несколько
  //: уровней: крошки шлют `back_to`, и стек укорачивается не на кадр, а на
  //: сколько придётся. Один `history.back()` увёл бы браузер на промежуточный
  //: адрес, а тот немедленно развернулся бы обратно в стек -- нажатие на
  //: крошку читалось бы как «вернулся и снова провалился».
  const trail = [];

  const onState = () => {
    const next = address();
    if (next === null || next === written) return;
    const prev = written;
    written = next;
    if (prev === null) {
      trail[depth] = next;
      window.history.replaceState({ of: depth }, "", next);
      return;
    }
    // Стек не вырос, а укоротился -- значит это возврат, и новой записи в
    // истории он не стоит: истории полагается уменьшиться, как от кнопки
    // «назад» браузера. Проверка -- буквально начало строки, и это верно
    // только потому, что каждый сегмент адреса закрыт косой чертой: раздел
    // `Tasks` не окажется началом раздела `TasksMore`.
    if (prev.startsWith(next)) {
      // Назад -- ровно до той своей записи, где этот адрес и стоял, сколько бы
      // их ни было между. Не «на одну»: снятых кадров бывает несколько разом.
      const at = trail.lastIndexOf(next, depth);
      if (at >= 0 && at < depth) {
        const steps = depth - at;
        depth = at;
        window.history.go(-steps);
        return;
      }
      // Такой записи позади нет: уходить некуда, и адрес правится на месте.
      trail[depth] = next;
      window.history.replaceState({ of: depth }, "", next);
      return;
    }
    depth += 1;
    trail[depth] = next;
    window.history.pushState({ of: depth }, "", next);
  };

  const onPop = () => {
    depth = window.history.state?.of ?? 0;
    const target = parseAddress(window.location.hash);
    const canon = target ? format(target) : null;
    // Собственный `history.go(-n)` возвращает нас туда, где стек уже стоит:
    // адрес сошёлся, делать нечего. Так же выглядит и повторное нажатие на
    // кнопку браузера, вернувшее к тому же самому месту.
    if (canon === address()) {
      written = canon;
      return;
    }
    // Чужой или устаревший адрес не двигает ничего: строку по стеку поправит
    // ближайшая запись, а стек останется стоять, где стоял.
    if (!target || !known(target.screen)) return;
    written = canon;
    go(target);
  };

  let unsubscribe = null;
  const watch = () => { unsubscribe = store.subscribe(onState); };

  const opened = parseAddress(window.location.hash);
  if (opened && known(opened.screen)) {
    written = format(opened);
    trail[0] = written;
    // Набранный руками адрес приводится к канону сразу: дальше он сравнивается
    // строкой, и «`#!/Tasks`» против «`#!/Tasks/`» разошлось бы на пустом месте.
    if (written !== window.location.hash) {
      window.history.replaceState({ of: 0 }, "", written);
    }
    // Подписка -- после ответа рантайма, а не до него, и это не осторожность.
    // Между событием и ответом склад успевает смениться по другим поводам:
    // состояние обмена приходит тем же тактом (`main.jsx`). Стек в этот миг
    // ещё корневой -- ссылка его только что заказала, -- и подписка «поправила
    // бы» строку по нему: адрес мигал бы корнем раздела, а на месте одной
    // записи истории оказывалось бы две. Одного «мы уже написали этот адрес»
    // мало: сторожит оно совпавший адрес, а тут приходит несовпавший.
    //
    // Ответ пришёл -- строка сверяется один раз руками, тем же правилом. Этим
    // же и правится ссылка, которую рантайм исполнить не смог: стек ответа
    // короче адреса, и адрес идёт за стеком, как ему и положено.
    (async () => {
      try {
        await go(opened);
      } catch {
        // Рантайм о своей беде говорит сам; строке от этого не легче, и
        // сверить её всё равно надо -- по тому стеку, который есть.
      }
      watch();
      onState();
    })();
  } else {
    watch();
  }

  window.addEventListener("popstate", onPop);
  return () => {
    unsubscribe?.();
    window.removeEventListener("popstate", onPop);
  };
}

/**
 * Ссылка в нативной сборке.
 *
 * Адресной строки в Capacitor нет: страница живёт по `capacitor://localhost`
 * (iOS) или `http://localhost` (Android), и `pushState` на несуществующий путь
 * там ломает перезапуск webview. Значит писать нечего, а читать надо не строку,
 * а событие.
 *
 * Дверей две, и обе обязательны: `appUrlOpen` -- ссылка, открытая при живом
 * приложении, `getLaunchUrl()` -- та, которой приложение запустили. Второе не
 * следствие первого: `appUrlOpen` при холодном старте выстреливает раньше, чем
 * рантайм готов его принять, и одной подпиской ссылка запуска теряется.
 */
function bindLaunchUrl(go) {
  let listener = null;
  let dead = false;
  (async () => {
    try {
      const { App } = await import("@capacitor/app");
      listener = await App.addListener("appUrlOpen", (ev) => go(parseAddress(ev.url)));
      if (dead) listener.remove();
      const launch = await App.getLaunchUrl();
      if (!dead && launch?.url) go(parseAddress(launch.url));
    } catch {
      // не Capacitor -- вязать нечего
    }
  })();
  return () => {
    dead = true;
    listener?.remove();
  };
}
